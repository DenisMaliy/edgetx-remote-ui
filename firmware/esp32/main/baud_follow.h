/**
 * @file baud_follow.h
 * @brief Міст іде за пультом при зміні швидкості каналу (ADR-0005).
 *
 * ## Чому міст нічого не вирішує
 *
 * Швидкість замовляє клієнт пакетом `0x88 BAUD_SET`, дозволяє її **пульт**
 * (перелік живе в прошивці), а міст лише виконує. Тому тут немає ані переліку
 * дозволених швидкостей, ані власного каналу керування: міст помічає
 * підтвердження `0x06 BAUD` у потоці, який і так розбирає, і йде слідом.
 *
 * ⚠️ Наслідок, який варто назвати вголос: **міст не мусить розуміти команду,
 * щоб її виконати.** Він читає відповідь пульта, а не запит клієнта. Так
 * будь-який клієнт — браузер, `tools/baud_probe.py`, майбутній застосунок —
 * отримує перемикання без жодного рядка в мості.
 *
 * ## Порядок, і чому саме такий
 *
 * Першим перемикається **пульт** — він робить це в мить, яку сам контролює
 * (коли його DMA дожував пачку). Підтвердження — останній кадр, який він шле
 * на старій швидкості, і в ньому лежить `switch_delay_ms`: обіцянка «я
 * перемкнусь не пізніше ніж через стільки». Міст чекає рівно це число й
 * перемикається другим. Порядок гарантується числом із пакета, а не збігом.
 *
 * ## Дорога назад — та сама, що в пульта
 *
 * Пульт, не почувши нікого за вікно повернення, іде на `BRIDGE_BAUDRATE`.
 * Міст мусить уміти те саме, інакше після відкату пульта вони розійдуться
 * назавжди: пульт удома, міст на чужій швидкості, і жоден не знає про іншого.
 *
 * ⚠️ Обидва йдуть **не «на попередню», а на ту саму константу**. Спільного
 * стану в них немає — після перезавантаження моста його не існує взагалі, —
 * тому єдине місце, де вони гарантовано зустрінуться, це число, відоме обом
 * до всякої розмови.
 */

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/** Готує стан. Викликається після `uart_link_init()`. */
void baud_follow_init(void);

/**
 * @brief Згодувати пакет, що прийшов від пульта.
 *
 * Цікавить рівно два випадки: `0x06 BAUD` з вердиктом «перемкнеться» — щоб
 * піти слідом, і **будь-який** валідний пакет — щоб знати, що пульт нас чує.
 *
 * @param type тип пакета
 * @param payload вантаж без обгортки
 * @param len довжина вантажу
 */
void baud_follow_on_packet(uint8_t type, const uint8_t *payload, size_t len);

/**
 * @brief Прохід у часі: перемкнутись, коли настав час, або піти додому.
 *
 * Викликається з тієї самої задачі, що читає UART, і **тільки** з неї:
 * перемикання чіпає той самий порт.
 *
 * ⚠️ Уся дія відбувається тут, а не в `baud_follow_on_packet()`, і це не
 * стиль. Обробник пакета виконується всередині розбирача; перемкнути там
 * означало б скинути розбирач посеред його ж роботи.
 *
 * @param now_us поточний час, `esp_timer_get_time()`
 * @return true, якщо швидкість щойно змінилась — викликач мусить скинути
 *         свій розбирач: усе, що лежало в ньому, приймалось на іншій швидкості
 */
bool baud_follow_tick(int64_t now_us);

/** Поточна швидкість каналу з боку моста. */
uint32_t baud_follow_current(void);
