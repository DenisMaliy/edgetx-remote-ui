/**
 * @file heap_watch.h
 * @brief Куди дівається вільна купа моста — і, головне, **коли саме**.
 *
 * ## Навіщо окремий прилад, якщо `heap_min` уже є
 *
 * `esp_get_minimum_free_heap_size()` монотонний від старту і **ніколи не
 * скидається**. Одне глибоке просідання за весь сеанс назавжди робить це число
 * своїм, і після нього воно вже не відповідає на жодне питання: ні «чи стало
 * гірше», ні «коли це сталося», ні «що міст тоді робив».
 *
 * Саме так і вийшло в задачі 0020: у розділ «Що не вийшло» потрапило 1.9 КБ
 * як властивість сеансу, тоді як насправді це слід **однієї миті** —
 * завантаження сторінки, — а решту сеансу вільними лишались ті самі 106 КБ.
 *
 * Тому тут три різні числа замість одного:
 *
 * 1. **мінімум за етапом** — окремо для спокою, потоку пікселів і віддачі
 *    сторінки. Це і є відповідь «хто з'їв», без здогадів;
 * 2. **мінімум у вікні** — скидається запитом, тобто замір можна почати з
 *    чистого аркуша, не перезавантажуючи міст;
 * 3. **перша хвилина проти останньої** — це перевірка на витік. Розмір
 *    лікується розміром, витік — ні, і плутати їх не можна.
 *
 * ## Контрольні точки старту
 *
 * Окремо від усього вище: скільки купи забирає кожен крок підняття моста.
 * Це відповідь на другу половину питання — **що зайнято постійно**, — і без
 * неї «купа скінчилась» не відрізнити від «купи стільки й було».
 */

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/** Що робив міст у мить, коли купа просіла. */
typedef enum {
    HEAP_PHASE_IDLE = 0, /**< ні телефона, ні віддачі файлів */
    HEAP_PHASE_STREAM,   /**< телефон під'єднаний: пікселі, ввід, лічильники */
    /**
     * Міст віддає файл сторінки по HTTP — і ще коротку мить після того, поки
     * віддане не зійшло з черги TCP.
     *
     * ⚠️ Межа між цим етапом і потоком **приблизна за побудовою**, і знати це
     * треба, читаючи `min_page`. Дізнатись, коли черга TCP справді спорожніла,
     * зсередини не можна, тож хвіст заданий часом (`HEAP_PAGE_TAIL_MS`).
     * Якщо браузер устигне відкрити WebSocket і отримати перший повний кадр
     * усередині цього хвоста, кадр запишеться сюди. На практиці не встигає —
     * між останнім файлом і сокетом лежить розбір самого `app.js`, — але
     * гарантії тут немає, і видавати її за гарантію не можна.
     */
    HEAP_PHASE_PAGE,
    HEAP_PHASE_COUNT
} heap_phase_t;

/** Людською мовою — для журналу й для панелі клієнта. */
const char *heap_phase_name(heap_phase_t phase);

/** Завести прилад. Кличеться першим рядком `app_main`. */
void heap_watch_init(void);

/**
 * @brief Контрольна точка підняття моста: «після цього кроку лишилось стільки».
 * @param what  короткий підпис; мусить пережити виклик (літерал).
 */
void heap_watch_mark(const char *what);

/**
 * @brief Знімок вільної купи. Кличеться часто, з `rx_task`.
 *
 * @param now_us  час, який задача вже має — щоб не питати його вдруге.
 *
 * ⚠️ **Роздільність — 8–10 мс, а не 1 мс.** Її задає виток `rx_task` (читання
 * UART із тайм-аутом 10 мс), а не обмежувач усередині. Просідання при віддачі
 * файлу триває сотні мілісекунд і ловиться десятками знімків; просідання на
 * дрібному файлі — того ж порядку, що й крок приладу, тож його дно може бути
 * глибшим за записане.
 *
 * ⚠️ Тут **не можна друкувати в журнал**. Консоль — синхронний запис у UART0
 * на 115200, тобто мілісекунди блокування задачі, про яку сказано «не має
 * права чекати». Попередження лише зводиться прапорцем, а друкує його сторож
 * через `heap_watch_take_warning()`.
 */
void heap_watch_sample(int64_t now_us);

/** Міст почав/скінчив віддавати файл сторінки. Кличеться із задачі httpd. */
void heap_watch_page_enter(void);
void heap_watch_page_leave(void);

/**
 * @brief Забрати невидане попередження про низьку купу.
 *
 * @param[out] free_bytes  скільки лишалось у ту мить
 * @param[out] phase       що міст тоді робив
 * @return `true`, якщо попередження було і його ще не друкували.
 *
 * Одноразове за весь час роботи: потік однакових рядків у синхронну консоль
 * зашкодив би більше за те, про що попереджає.
 */
bool heap_watch_take_warning(uint32_t *free_bytes, const char **phase);

/** Мінімум у поточному вікні заміру. */
uint32_t heap_watch_window_min(void);

/**
 * @brief Почати нове вікно заміру: мінімум = вільно зараз.
 *
 * Перезапускає **вікно і перевірку на витік**, але навмисно **не чіпає
 * мінімумів за етапом**: ті відповідають на питання «хто з'їв за все життя
 * цього завантаження», і обнуляти їх щоразу, коли починається новий замір,
 * означало б втрачати рідкісні події — саме ті, заради яких прилад і
 * будувався.
 */
void heap_watch_window_reset(void);

/** Прилад у JSON — вкладеним об'єктом, без зовнішніх дужок. */
size_t heap_watch_json(char *out, size_t cap);
