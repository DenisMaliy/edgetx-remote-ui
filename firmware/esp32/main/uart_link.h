/**
 * @file uart_link.h
 * @brief Канал до пульта: UART на 921600.
 */

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "esp_err.h"
#include "stats.h"

esp_err_t uart_link_init(void);

/**
 * @brief Прочитати те, що вже прийшло від пульта.
 * @return скільки байтів прочитано; 0 — у каналі тиша (це не помилка).
 */
int uart_link_read(uint8_t *buf, size_t cap, uint32_t timeout_ms);

/**
 * @brief Забрати з черги драйвера події втрати.
 *
 * Переповнення апаратної черги або буфера приймання означає, що байти
 * загубились **на вході в міст** — це третє місце втрат, окреме і від
 * пульта, і від Wi-Fi. Без цього лічильника втрачені байти виглядали б як
 * помилки CRC, тобто як псування на дроті, і шукали б не там.
 */
void uart_link_poll_events(void);

/**
 * @brief Переслати байти пульту як є.
 *
 * Міст їх не тлумачить: що клієнт надіслав, те й іде на дріт.
 */
int uart_link_write(const uint8_t *data, size_t len);

/**
 * @brief Відпустити весь ввід на пульті — обнулений `INPUT_STATE`.
 *
 * ⚠️ Викликається **негайно** при втраті телефона, а не за тайм-аутом.
 * Пряма вимога протоколу, записана саме заради моста: він власний посередник
 * і цілком може слати `PING` далі після того, як телефона вже немає, а
 * клавіша лишиться натиснутою — і людина цього не побачить, екрана немає.
 *
 * ⚠️ Причина потрібна не лише лічильникам, а й людині коло монітора: раніше
 * тут стояв прапорець «мовчання чи розрив», і на **чистому старті** міст
 * друкував «телефон зник (розрив)», хоча телефона не було жодного разу.
 * Повідомлення, що називає неіснуючу подію, — гірше за відсутнє.
 *
 * @param reason що саме сталося; впливає на лічильники і на рядок у журналі
 */
void uart_link_send_input_release(bridge_lost_t reason);
