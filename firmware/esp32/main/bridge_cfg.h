/**
 * @file bridge_cfg.h
 * @brief Усі налаштовувані числа моста в одному місці.
 *
 * Специфіка плати живе тут і більше ніде. У решті коду не має бути ані
 * номера піна, ані назви цілі — те саме правило, що й у прошивці пульта
 * (CLAUDE.md: «специфіка конкретного пульта в коді — нуль рядків»).
 */

#pragma once

#include "driver/uart.h"

/* ---------------------------------------------------------------- канал --*/

/** Швидкість каналу до пульта при старті. ADR-0003, ADR-0005.
 *
 * ⚠️ Тепер це **початкова й домашня** швидкість, а не єдина. Пульт уміє
 * перемикатись на ходу командою протоколу і сам вертається сюди, якщо після
 * перемикання нікого не почув. Міст мусить піднімати цю саму константу, бо
 * після його перезавантаження це єдине місце, де вони гарантовано
 * зустрінуться: спільного стану в них немає.
 */
#ifndef BRIDGE_BAUDRATE
#define BRIDGE_BAUDRATE 921600
#endif

/**
 * Найвища швидкість, на яку міст може погодитись.
 *
 * ⚠️ Це число визначає розмір приймального буфера нижче, а не навпаки. Стеля
 * пульта — 2 625 000 = PCLK1/16 (`remote_ui/baudrate.h`); якщо перелік у
 * прошивці колись зміниться, тут має змінитись теж, інакше буфер виявиться
 * замалим мовчки.
 */
#if CONFIG_IDF_TARGET_ESP32
#define BRIDGE_UART_MAX_BAUD 2625000
#else
/* C3: одне ядро, Wi-Fi і приймання змагаються за нього — 921600 лишається
 * стелею, доки хтось не поміряє. */
#define BRIDGE_UART_MAX_BAUD 921600
#endif

/**
 * Найгірша заміряна затримка задачі, що читає UART.
 *
 * ⚠️ Не оцінка й не круглий запас: **заміряне число** із задачі 0013,
 * `beat_interval_max_ms` за десять хвилин при завантаженні каналу 90%. Саме
 * стільки міст може не заглядати в буфер, і саме стільки той мусить тримати.
 */
#define BRIDGE_UART_WORST_LATENCY_MS 132

/* ------------------------------------------------------------ розпіновка --*/

#if CONFIG_IDF_TARGET_ESP32

/* ESP32 DevKit v1 (WROOM-32) — плата для розробки.
 *
 * UART0 (GPIO1/3) зайнятий логами через штатний перетворювач, тому UART1.
 * GPIO16/17 на WROOM-32 вільні (на WROVER їх забирає PSRAM — цієї плати це
 * не стосується).
 *
 * Приймання закріплюємо за ядром 1, Wi-Fi лишається на ядрі 0. Це головна
 * перевага цієї плати над C3 і причина, чому розробка йде саме на ній. */
#define BRIDGE_UART_PORT UART_NUM_1
#define BRIDGE_PIN_RX 16 /* ← до TX пульта (AUX1) */
#define BRIDGE_PIN_TX 17 /* ← до RX пульта (AUX1) */
#define BRIDGE_RX_CORE 1
/* 48 КіБ = 187 мс потоку на 2 625 000 бод. Виведення — біля
 * BRIDGE_UART_WORST_LATENCY_MS; перевіряється _Static_assert у uart_link.c. */
#define BRIDGE_UART_RX_BUF 49152
#define BRIDGE_WS_RING_BYTES 24576

#elif CONFIG_IDF_TARGET_ESP32C3

/* ESP32-C3 SuperMini — кандидат у корпус. Одне ядро: Wi-Fi і приймання
 * змагаються за нього, тому буфери менші, а 921600 — стеля.
 *
 * ⚠️ НЕ GPIO20/21, хоча саме вони стояли в старому platformio.ini. Це
 * штатні піни UART0, і на них ПЗП-завантажувач друкує свій журнал **до**
 * того, як наш код отримає керування, — тобто пульт при кожному
 * перезавантаженні моста отримував би сміття в AUX1. Пульт його відкине по
 * CRC, але дірка в кадрі буде рівно в момент, коли людина дивиться на екран.
 * GPIO4/5 вільні: 8 — світлодіод, 9 — boot, 20/21 — UART0.
 *
 * ⚠️ Розпіновка C3 ще не проходила `hw-integration` — перед першим
 * підключенням C3 це обов'язково (CLAUDE.md). DevKit v1 цього не потребує:
 * його вже перевіряли на кроці 2.4. */
#define BRIDGE_UART_PORT UART_NUM_1
#define BRIDGE_PIN_RX 4
#define BRIDGE_PIN_TX 5
#define BRIDGE_RX_CORE 0
/* 16 КіБ = 178 мс на 921600 — те саме правило, що для DevKit.
 * ⚠️ Плати C3 на руках немає, це число не перевірене на залізі. */
#define BRIDGE_UART_RX_BUF 16384
#define BRIDGE_WS_RING_BYTES 12288

#else
#error "Ціль не описана в bridge_cfg.h — додай розпіновку, не вгадуй"
#endif

/* ------------------------------------------------------------------ Wi-Fi --*/

#ifndef BRIDGE_WIFI_SSID
#define BRIDGE_WIFI_SSID "TX16S-RemoteUI"
#endif

/**
 * ⚠️ **Пароль лежить у відкритому репозиторії, тобто захисту тут немає.**
 *
 * Формально мережа закрита, фактично — та сама відкрита: пароль знає кожен,
 * хто бачив цей файл, а через цю мережу **керують пультом**. Поки стенд на
 * столі, це байдуже. До етапу 3 треба або пароль, похідний від MAC плати,
 * або зміну без перезбирання (рішення від 2026-07-27, `state/DECISIONS.md`).
 *
 * Тут навмисно немає заспокійливого коментаря: він був, і він брехав.
 */
#ifndef BRIDGE_WIFI_PASS
#define BRIDGE_WIFI_PASS "tx16sremote"
#endif

#ifndef BRIDGE_WIFI_CHANNEL
#define BRIDGE_WIFI_CHANNEL 6
#endif

/** Потужність передавача в одиницях 0.25 дБм: 34 = 8.5 дБм.
 *  До телефона метр, повна потужність ні до чого, а поруч працює
 *  радіомодуль пульта. Стеля драйвера — 84 (21 дБм), підлога — 8. */
#ifndef BRIDGE_WIFI_TX_POWER
#define BRIDGE_WIFI_TX_POWER 34
#endif

/* -------------------------------------------------- пріоритети задач -----*/

/**
 * ⚠️ Найважливіша задача в цьому переліку — **не наша**. Ввід від телефона
 * розбирає задача сервера httpd, і її пріоритет ставить ESP-IDF
 * (`HTTPD_DEFAULT_CONFIG()`, зараз `tskIDLE_PRIORITY + 5`). Наші числа
 * записані так, ніби її не існує, тож `ws_tx_task` на 6 стоїть **вище** за
 * неї і формально має право її витісняти.
 *
 * Задача 0013 підозрювала саме це — і **спростувала заміром**. Прилад:
 * `rx_task` б'є в задачу сервера раз на 100 мс, і `beat_interval_max_ms`
 * показує, наскільки та затрималась. За 10 хвилин при завантаженні каналу
 * 90%, коли паузи між пакетами вводу сягали 4196 мс, биття лишилось
 * **132 мс проти 129 у спокої** — тобто задача вводу процесор отримувала
 * вчасно **весь час**. Причина пауз виявилась зовсім не тут.
 *
 * Тому числа лишаються як були: міняти робочий розклад реального часу без
 * підстави — гірше, ніж лишити його. Але зв'язок із чужим числом більше не
 * невидимий: він друкується на старті, а `beat_interval_max_ms` лишається приладом,
 * яким це перевіряють знову — насамперед після переходу на 2 Мбод, де черга
 * до Wi-Fi спорожнюватиметься інакше.
 */
#define BRIDGE_PRIO_RX 12      /**< приймання з UART: не має права чекати */
#define BRIDGE_PRIO_WS_TX 6    /**< віддача пікселів у Wi-Fi */
#define BRIDGE_PRIO_WATCHDOG 4 /**< сторож мовчання: дешевий і мусить встигати */

/* ----------------------------------------------------------- тайм-аути ---*/

/**
 * Скільки мовчання клієнта означає «телефон зник».
 *
 * Клієнт зобов'язаний слати `INPUT_STATE` раз на 250 мс безумовно
 * (docs/03-protocol.md), тож 750 мс — три пропущені періоди. Число менше за
 * тайм-аут відпускання в прошивці (1000 мс) навмисно: міст має помітити
 * втрату **раніше** за пульт і відпустити ввід сам, а не покластися на
 * останню перешкоду.
 */
#define BRIDGE_CLIENT_SILENCE_MS 750

/** Період сторожа, що стежить за мовчанням клієнта. */
#define BRIDGE_WATCHDOG_PERIOD_MS 100

/** Період биття, яким міряється затримка задачі, що чує ввід. */
#define BRIDGE_HEARTBEAT_MS 100

/**
 * Скид розбирача після тиші в каналі.
 *
 * ⚠️ **Те саме число, що в прошивці пульта** (`SILENCE_RESET_MS` у
 * `transport_simu.cpp` і `transport_uart.cpp`) і в `tools/remote_ui_proto.py`
 * (`SILENCE_RESET_S`). Воно описує **протокол**, а не трубу, тож три
 * примірники мусять збігатися: найбільший кадр (4103 Б) на 921600 бод іде
 * ~45 мс, тобто вдвічі менше за поріг.
 *
 * Обов'язок транспортного шару, бо в кадруванні часу немає: воно не знає,
 * скільки минуло між байтами (`docs/03-protocol.md`).
 */
#define BRIDGE_SILENCE_RESET_MS 100

/**
 * Скільки відправлень поспіль мають не вдатися, щоб визнати сокет мертвим.
 *
 * ⚠️ Одне невдале відправлення — це затор у TCP, а не зниклий телефон.
 * Рішення «телефона немає» належить сторожу мовчання; черга передачі має
 * право лише викинути пачку. П'ять поспіль при пачці раз на ~10 мс — це вже
 * не затор.
 */
#define BRIDGE_WS_SEND_FAILS_MAX 5

/* ------------------------------------------------------------- передача --*/

/**
 * Скільки байтів міст збирає в один кадр WebSocket.
 *
 * ⚠️ Це **не** накопичення кадру екрана. Повний кадр — 255 КБ і не влазить у
 * жодну з плат (ADR-0003); тут лежить щонайбільше два пакети протоколу,
 * бо стеля одного — 4103 Б. Збирати їх у пачку треба, інакше на кожну
 * дрібну плитку йшов би окремий кадр WebSocket зі своїм заголовком і своїм
 * пакетом TCP.
 */
#define BRIDGE_WS_CHUNK_BYTES 8192

/**
 * Скільки часу міст дозаписує залишок недописаного кадру WebSocket.
 *
 * ⚠️ Не «скільки чекати», а «скільки коштує не зіпсувати потік». Обрізаний
 * кадр невиправний: кадрування WebSocket самосинхронізації не має, і клієнт
 * після нього читає вантаж як заголовок (див. `send_all` у `ws_bridge.c`).
 * Тому дозапис вартий очікування — але не нескінченного: `ws_tx_task` тим
 * часом не вичерпує чергу, і за 3 с при 262 КБ/с у неї приходить 786 КБ на
 * 24 КБ місця. Не встигли — гасимо сокет, це чесніше за сміття в клієнті.
 *
 * Ціле число тайм-аутів `send_wait_timeout` (2 с) сюди не вкладається
 * навмисно: бюджет міряє **сумарний** час, а не кількість спроб.
 */
#define BRIDGE_WS_SEND_BUDGET_MS 3000

/** Скільки байтів приймає міст від клієнта за один кадр WebSocket.
 *  Найбільший пакет у цьому напрямку — `INPUT_STATE`, 20 Б на дроті. */
#define BRIDGE_WS_RX_MAX 1024
