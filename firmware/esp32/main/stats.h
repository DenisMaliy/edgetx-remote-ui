/**
 * @file stats.h
 * @brief Лічильники моста. Не прикраса, а прилад.
 *
 * Задача 0011 вимагає розрізняти **два різні місця втрат**: скільки плиток
 * відкидає міст і скільки пульт. Без лічильників на це не відповісти, а
 * «здається, підлагує» — не результат. У 0010 саме заміри показали, що
 * винен насичений дріт, а не архітектура.
 *
 * Лічильники пишуться **без замків**, і це свідомо. Більшість має рівно
 * одного писаря (`rx_task`, `ws_tx_task` або задача httpd), але не всі:
 * `input_releases`, `silence_timeout`, `clients_lost` пишуться з кількох
 * місць — обробника закриття сокета, події Wi-Fi і сторожа. Там гонка
 * коштує **одиниці в лічильнику**, не більше: жодне рішення на них не
 * приймається, вони лише показуються людині. Читає їх `/api/stats`, якому
 * точність до одиниці не потрібна.
 *
 * ⚠️ Якщо колись на лічильнику з'явиться рішення — його доведеться взяти
 * під той самий замок, що й стан з'єднання.
 */

#pragma once

#include <stddef.h>
#include <stdint.h>

/**
 * @brief Чому сеанс із телефоном скінчився.
 *
 * ⚠️ Задача 0012 показала гірший із можливих випадків: сеанс помер, і **жоден
 * лічильник не ворухнувся**. Наслідок не в тому, що бракує числа, а в тому,
 * що причину шукатимуть у Wi-Fi, живленні й конденсаторах — тобто там, де її
 * немає. Ця табличка існує рівно для того, щоб міст **називав** те, що
 * зробив, а не лишав здогадуватись.
 *
 * `BRIDGE_LOST_SILENCE` тут стоїть окремо і сеансом не рахується: сторож
 * мовчання відпускає ввід, але сокет **не рве** (рішення 2026-07-27).
 */
typedef enum {
    BRIDGE_LOST_BOOT,      /**< телефона не було: міст щойно стартував */
    BRIDGE_LOST_EVICTED,   /**< керування перейняв інший телефон — на вимогу */
    /**
     * Господар повернувся на власний слот: сокет його сторінки помер, а міст
     * ще числив його живим (задача 0024, `resume`).
     *
     * ⚠️ Окремо від `BRIDGE_LOST_EVICTED` навмисно: витіснення — це подія, яку
     * бачить **людина** (у неї забрали пульт), а повернення свого не бачить
     * ніхто. Злиті в одне число, вони зробили б критерій «гойдалки більше
     * немає» недоказовим: різниця `lost_evicted` має бути нулем, і сплутати з
     * нею звичайне перепідключення телефона не можна.
     */
    BRIDGE_LOST_RESUMED,
    BRIDGE_LOST_SEND_FAIL, /**< кілька відправлень поспіль не вдалося */
    BRIDGE_LOST_OVERSIZED, /**< кадр від клієнта понад стелю — це не наш клієнт */
    BRIDGE_LOST_WS_CLOSE,  /**< клієнт попрощався штатно */
    BRIDGE_LOST_SOCKET,    /**< сокет помер сам: спрацював `close_fn` */
    /**
     * ⚠️ Телефон вийшов із мережі Wi-Fi, і в ній не лишилось нікого.
     *
     * Окремо від `BRIDGE_LOST_SOCKET` навмисно, і це не педантизм: тут сокет
     * **не помирав**, це наше власне рішення його погасити. Поки причина була
     * спільна, кожен вихід із мережі зараховувався ще й у `socket_silent` —
     * тобто в те єдине число, яким доводять «сеанс помер піді мною». Доказ,
     * який спрацьовує на чужій події, гірший за відсутній.
     */
    BRIDGE_LOST_WIFI,
    BRIDGE_LOST_SILENCE,   /**< ⚠️ не розрив: ввід відпущено, сокет живий */
} bridge_lost_t;

/** Людською мовою — для журналу монітора. */
const char *bridge_lost_name(bridge_lost_t reason);

typedef struct {
    /* --- пульт → міст ---------------------------------------------------- */
    uint32_t uart_bytes;   /**< байтів прочитано з UART */
    uint32_t packets_ok;   /**< цілих пакетів розібрано */
    uint32_t crc_errors;   /**< відкинуто по CRC — псування на дроті */
    uint32_t oversized;    /**< брехлива довжина понад 4096 */
    uint32_t tiles_in;     /**< з них плиток */
    uint32_t frames_in;    /**< з них FRAME_END, тобто цілих кадрів */
    uint32_t uart_dropped;   /**< драйвер UART не встиг: переповнення */
    uint32_t silence_resets; /**< розбирач скинуто за тишею посеред кадру */

    /* --- міст → телефон -------------------------------------------------- */
    uint32_t ws_bytes;        /**< байтів віддано у WebSocket */
    uint32_t ws_chunks;       /**< пачок віддано */
    uint32_t ws_errors;       /**< невдалих відправлень */
    uint32_t tiles_dropped;   /**< ⚠️ плиток відкинуто мостом: Wi-Fi не встиг */
    uint32_t packets_dropped; /**< пакетів відкинуто мостом разом із ними */
    uint32_t chunks_dropped;  /**< пачок відкинуто: черга до Wi-Fi повна */
    uint32_t chunks_noclient; /**< пачок викинуто, бо телефона немає */
    uint32_t send_dropped;    /**< пачок викинуто: затор у TCP, сеанс живий */

    /* --- чому саме не вдалося відправити (сума дорівнює `ws_errors`) ------ */
    /**
     * ⚠️ Задача 0018 вимагає розрізнити три причини втрати, і дві з них
     * зовні однакові: «черга до Wi-Fi повна» видно в `chunks_dropped`, а от
     * «затор у TCP» і «в мості скінчилась пам'ять» досі зливались в одне
     * `send_dropped`. Різниця не косметична: перше — нормальна робота під
     * навантаженням, друге — межа виживання моста, при якій 20 КБ вільної
     * купи стають нулем.
     *
     * Розділяються за `errno`, який `send()` лишає під невдалим
     * `httpd_ws_send_frame_async`. Коли помилка сталася **до** самого
     * `send()` (не той сокет, не WebSocket), `errno` не про неї — такі
     * потрапляють у `send_err_other`.
     */
    uint32_t send_err_nomem; /**< ENOMEM/ENOBUFS: пам'ять, а не затор */
    uint32_t send_err_again; /**< EAGAIN/EWOULDBLOCK: вікно TCP зачинене */
    uint32_t send_err_conn;  /**< EPIPE/ECONNRESET/ENOTCONN: сокет мертвий */
    uint32_t send_err_other; /**< решта, зокрема помилки до send() */
    /** Останні коди, як є. Потрібні саме тому, що передбачити набір `errno`
     *  у lwIP наперед не вийшло — `other` без них нічого не каже. */
    int32_t send_err_last;
    int32_t send_errno_last;

    /**
     * ⚠️ Найдовше відправлення, мс. Без нього розкладка причин читається
     * навиворіт: `send_wait_timeout` — 2 с, тобто «вікно TCP зачинене» це
     * не мить, а дві секунди сну задачі передачі. За них черга переповниться
     * гарантовано, і `chunks_dropped` виглядатиме причиною, будучи
     * наслідком.
     */
    uint32_t send_ms_max;

    /**
     * ⚠️ Скільки разів `send()` записав **не все** і залишок довелось
     * дописувати. Штатний шлях ESP-IDF цього не бачить узагалі: lwIP при
     * спливанні `SO_SNDTIMEO` віддає часткове відправлення **як успіх**
     * (`api_msg.c:1745-1754`), а `httpd_ws_send_frame_async` перевіряє лише
     * `< 0` і циклу дозапису не має.
     */
    uint32_t send_partial;
    /**
     * ⚠️ Скільки кадрів WebSocket усе-таки пішли обрізаними. Кожен —
     * зіпсований потік і загашений сокет: кадрування WebSocket
     * самосинхронізації не має. Найімовірніший винуватець «сеанс помер, а
     * лічильники нулі» із задачі 0012 — тоді це успіхом і рахувалось.
     */
    uint32_t send_truncated;

    /** Найменший запас стека задачі httpd, байтів. Буфер JSON лежить саме
     *  там, і переповнення дало б паніку моста, схожу на просадку живлення. */
    uint32_t httpd_stack_free;

    /* --- розмір пачки (критерій 3 задачі 0018) --------------------------- */
    /**
     * ⚠️ `ws_chunks` і `ws_bytes` рахують лише **успішно відправлене**, тож
     * середній розмір по них зміщений: найбільші пачки — саме ті, що гинуть.
     * Ця пара рахує все зібране, до будь-яких втрат.
     *
     * Заразом це перевірка припущення: `BRIDGE_WS_CHUNK_BYTES` дорівнює
     * 8192, але пачку закриває кожен виток `rx_task`, а той читає
     * щонайбільше `sizeof(rd)` байтів за раз. Тобто справжній розмір пачки
     * задає буфер читання, а не константа з назвою «розмір пачки».
     */
    uint32_t chunks_built;      /**< пачок зібрано, до втрат */
    uint32_t chunk_bytes_built; /**< сумарно байтів у них */
    uint32_t chunk_len_max;     /**< найбільша зібрана пачка */
    /**
     * Найменша пачка, яку черга до Wi-Fi ще прийняла б, у найгіршу мить.
     *
     * ⚠️ Це **не** «вільне місце», хоч так і проситься прочитати.
     * `xRingbufferGetCurFreeSize` для `RINGBUF_TYPE_NOSPLIT` віддає
     * найбільший **суцільний** проміжок мінус заголовок і додатково обрізає
     * його по `xMaxItemSize = align(розмір/2) − 8` (`ringbuf.c:233`). Для
     * черги на 24576 Б стеля виходить **12280**, і саме це число стоїть тут
     * на порожній черзі. Прочитане як «вільно 12 КБ із 24» воно збрехало б
     * рівно навпіл.
     *
     * Порівнювати треба не з розміром черги, а з `chunk_len_max`: якщо
     * найменше значення досі більше за найбільшу пачку, черга не впиралась.
     */
    uint32_t ring_free_min;

    /* --- телефон → пульт ------------------------------------------------- */
    uint32_t client_bytes;   /**< байтів переслано в UART */
    uint32_t client_packets; /**< з них цілих пакетів (для звірки) */
    uint32_t client_input;   /**< з них таких, що несуть ввід */

    /* --- швидкість каналу (ADR-0005) ------------------------------------- */
    /** Поточна швидкість каналу з боку моста. */
    uint32_t baud_current;
    /**
     * ⚠️ Два лічильники відкоту, а не один, і це не педантизм.
     *
     * `baud_bridge_reverts` — «я не почув пульта». `baud_radio_reverts` — «пульт
     * не почув мене», число приходить у пакеті `0x06` від самого пульта.
     * Це різні події з різними причинами, і злити їх в одне число означало б
     * втратити рівно ту половину діагностики, яка каже, на чиєму боці шукати.
     */
    uint32_t baud_bridge_reverts;
    uint32_t baud_radio_reverts;

    /* --- з'єднання ------------------------------------------------------- */
    uint32_t clients_seen;    /**< скільки разів телефон під'єднувався */
    uint32_t clients_lost;    /**< скільки разів зникав */
    uint32_t input_releases;  /**< скільки разів слали обнулений INPUT_STATE */
    uint32_t silence_timeout; /**< з них — за мовчанням клієнта, а не за розривом */

    /* --- черга: хто господар (задача 0024) -------------------------------- */
    /**
     * Скільки разів прибульцю сказали «зайнято» — тобто скільки разів
     * **не** сталося витіснення, яке сталося б раніше.
     *
     * ⚠️ Це і є число, що відрізняє чергу від гойдалки: доти кожен такий
     * прихід ставав `lost_evicted`, а витіснений повертався через секунду.
     */
    uint32_t busy_refused;
    uint32_t takeovers;    /**< свідомих перейнять керування кнопкою */
    uint32_t resumes;      /**< повернень господаря на власний слот */
    uint32_t status_polls; /**< запитів `/api/status` — ціна очікування в черзі */

    /* --- чому саме зникав (сума дорівнює `clients_lost`) ------------------ */
    uint32_t lost_evicted;   /**< керування перейняв інший телефон */
    uint32_t lost_resumed;   /**< господар повернувся на власний слот */
    uint32_t lost_send_fail; /**< кілька відправлень поспіль не вдалося */
    uint32_t lost_oversized; /**< кадр понад стелю */
    uint32_t lost_ws_close;  /**< штатне прощання */
    uint32_t lost_socket;    /**< сокет помер сам */
    uint32_t lost_wifi;      /**< телефон вийшов із мережі, у ній нікого не лишилось */
    /** ⚠️ З них — **мовчазних**: `close_fn` спрацював, а `ws_errors` за весь
     *  сеанс не зросли. Це і є «помер піді мною» із задачі 0012, і саме цей
     *  рядок відрізняє його від «міст сам закрив». */
    uint32_t lost_socket_silent;

    /* --- пауза між пакетами вводу ---------------------------------------- */
    /**
     * Міряється **на боці моста**, тобто в момент, коли пакет розібрала задача
     * httpd. Це навмисно: різниця між «клієнт надіслав» і «міст побачив»
     * і є відповіддю на питання, хто саме не встиг.
     *
     * ⚠️ Наскрізні від старту моста, як і решта. Спершу вони обнулялись при
     * кожному під'єднанні — щоб «найдовша пауза» стосувалась поточного сеансу.
     * Це довелось прибрати, і причина варта запису: подія, заради якої прилад
     * і писався, **закінчується перепідключенням**. Тобто обнулення стирало
     * рівно той доказ, по який його ставили — у першому ж прогоні максимум
     * поїхав назад із 495 на 467 мс, і сплеск зник разом із сеансом.
     * Межа проби — перезавантаження моста, а не сеанс.
     */
    uint32_t gap_max_ms;  /**< найдовша пауза за поточний сеанс */
    uint32_t gap_le_300;  /**< пауз до 300 мс — норма при періоді 250 */
    uint32_t gap_le_500;  /**< 300…500 мс — клієнт затнувся, запас ще є */
    uint32_t gap_le_750;  /**< 500…750 мс — на межі спрацювання сторожа */
    uint32_t gap_over;    /**< понад поріг: сторож мав право відпустити ввід */
    /** Пауза, що спричинила останнє відпускання за мовчанням, цілком.
     *  Відома лише коли приїхав наступний пакет вводу — до того сторож знає
     *  тільки «більше за поріг». */
    uint32_t gap_after_release_ms;

    /* --- чи задача вводу взагалі отримувала процесор --------------------- */
    /**
     * ⚠️ Прилад, який відрізняє дві причини довгої паузи, зовні однакові:
     * «пакет затримався в ефірі» і «пакет лежав розібраний, бо задача, що
     * його розбирає, не діставала процесора».
     *
     * Влаштований так: `rx_task` (наш найвищий пріоритет, власне ядро) раз на
     * `BRIDGE_HEARTBEAT_MS` просить сервер httpd виконати **в його власній
     * задачі** порожню роботу. Різниця між двома такими позначками і є
     * затримка планування саме тієї задачі, яка чує ввід телефона.
     *
     * Читати разом із `gap_max_ms`. Якщо вони збігаються — процесор; якщо
     * биття рівне, а паузи великі — ефір або мережевий стек.
     */
    /**
     * ⚠️ Це **інтервал між пробудженнями**, а не чиста затримка: у ньому
     * сидить сам період биття (`BRIDGE_HEARTBEAT_MS`) плюс тремтіння
     * `rx_task`, чий виток прив'язаний до читання UART. Тому в спокої тут
     * ~130 мс при періоді 100, і це норма, а не затримка в 130 мс.
     * Читати як «період биття + приблизно 30 мс»; зміниться період —
     * зміниться й базовий рівень.
     */
    uint32_t beat_interval_max_ms;
    uint32_t hb_beats; /**< скільки разів биття дійшло */
    /**
     * ⚠️ Майже завжди нуль **за побудовою**, і доказом чогось не є:
     * керівний сокет `httpd` — UDP на петлі, і при переповненні черги lwIP
     * тихо викидає дейтаграму, а `sendto()` віддає успіх. Втрачений удар
     * лише **збільшує** інтервал вище, тож малий інтервал лишається
     * доказом; а от «черга жодного разу не була повна» не доводить нічого.
     */
    uint32_t hb_queue_full;
} bridge_stats_t;

extern bridge_stats_t g_stats;

/**
 * @brief Скласти JSON зі станом моста.
 * @return скільки байтів записано (без кінцевого нуля).
 */
size_t bridge_stats_json(char *out, size_t cap);
