/**
 * @file stats.h
 * @brief Лічильники моста. Не прикраса, а прилад.
 *
 * Задача 0011 вимагає розрізняти **два різні місця втрат**: скільки плиток
 * відкидає міст і скільки пульт. Без лічильників на це не відповісти, а
 * «здається, підлагує» — не результат. У 0010 саме заміри показали, що
 * винен насичений дріт, а не архітектура.
 *
 * Лічильники пишуться без замків: кожен із них має рівно одного писаря
 * (`rx_task`, `ws_tx_task` або задача httpd), а `input_releases` пишеться
 * рідко й з двох місць — там гонка коштувала б одиниці в лічильнику, не
 * більше. Читає їх `/api/stats`, якому точність до одиниці не потрібна.
 */

#pragma once

#include <stddef.h>
#include <stdint.h>

typedef struct {
    /* --- пульт → міст ---------------------------------------------------- */
    uint32_t uart_bytes;   /**< байтів прочитано з UART */
    uint32_t packets_ok;   /**< цілих пакетів розібрано */
    uint32_t crc_errors;   /**< відкинуто по CRC — псування на дроті */
    uint32_t oversized;    /**< брехлива довжина понад 4096 */
    uint32_t tiles_in;     /**< з них плиток */
    uint32_t frames_in;    /**< з них FRAME_END, тобто цілих кадрів */
    uint32_t uart_dropped; /**< драйвер UART не встиг: переповнення */

    /* --- міст → телефон -------------------------------------------------- */
    uint32_t ws_bytes;        /**< байтів віддано у WebSocket */
    uint32_t ws_chunks;       /**< пачок віддано */
    uint32_t ws_errors;       /**< невдалих відправлень */
    uint32_t tiles_dropped;   /**< ⚠️ плиток відкинуто мостом: Wi-Fi не встиг */
    uint32_t packets_dropped; /**< пакетів відкинуто мостом разом із ними */
    uint32_t chunks_dropped;  /**< пачок відкинуто: черга до Wi-Fi повна */
    uint32_t chunks_noclient; /**< пачок викинуто, бо телефона немає */

    /* --- телефон → пульт ------------------------------------------------- */
    uint32_t client_bytes;   /**< байтів переслано в UART */
    uint32_t client_packets; /**< з них цілих пакетів (для звірки) */
    uint32_t client_input;   /**< з них таких, що несуть ввід */

    /* --- з'єднання ------------------------------------------------------- */
    uint32_t clients_seen;    /**< скільки разів телефон під'єднувався */
    uint32_t clients_lost;    /**< скільки разів зникав */
    uint32_t input_releases;  /**< скільки разів слали обнулений INPUT_STATE */
    uint32_t silence_timeout; /**< з них — за мовчанням клієнта, а не за розривом */
} bridge_stats_t;

extern bridge_stats_t g_stats;

/**
 * @brief Скласти JSON зі станом моста.
 * @return скільки байтів записано (без кінцевого нуля).
 */
size_t bridge_stats_json(char *out, size_t cap);
