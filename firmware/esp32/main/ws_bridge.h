/**
 * @file ws_bridge.h
 * @brief Сервер: сторінка клієнта по HTTP і потік протоколу по WebSocket.
 */

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "esp_err.h"

/**
 * @brief Підготувати стан. Викликати **до** підняття Wi-Fi.
 *
 * ⚠️ Окремо від `ws_bridge_start()` навмисно. Замок стану має існувати
 * раніше, ніж з'явиться перше джерело подій: `esp_wifi_start()` уже здатен
 * покликати обробник події, а той — узяти ще не створений замок. Паніка в
 * цьому вікні виглядала б **точно як просадка живлення від кидка струму**,
 * про яку попереджає `BRINGUP.md`, і шукали б її в конденсаторі.
 */
esp_err_t ws_bridge_init(void);

esp_err_t ws_bridge_start(void);

/** Чи є зараз під'єднаний телефон. */
bool ws_bridge_has_client(void);

/** Сокет телефона, або -1. Брати перед рішенням, діяти — з ним. */
int ws_bridge_client_fd(void);

/**
 * @brief Віддати пачку байтів телефону.
 *
 * Викликається з `ws_tx_task` і має право блокуватись: черга перед ним
 * скінченна, і саме її переповнення означає «Wi-Fi не встигає».
 *
 * @return ESP_OK або помилка; помилка означає, що телефона більше немає.
 */
esp_err_t ws_bridge_send(const uint8_t *data, size_t len);

/**
 * @brief Ввід застарів — відпустити його, **не чіпаючи сокет**.
 *
 * ⚠️ «Ввід застарів» і «телефона немає» — два різні висновки, і плутати їх
 * не можна. Браузери душать таймери у вкладці, яку сховали, тож згаслий
 * екран телефона легко дає мовчання довше за поріг. Розрив сокета коштував
 * би перепідключення плюс повний `REFRESH` на 20–40 КБ — саме там, де ми
 * міряємо затримку. Відпустити ввід у цьому разі треба, рвати зв'язок — ні.
 *
 * Відпускає один раз на епізод мовчання; наступний пакет із вводом знімає
 * засувку.
 *
 * @return true, якщо ввід щойно відпущено.
 */
bool ws_bridge_release_if_silent(uint32_t silence_ms);

/**
 * @brief Оголосити телефон загубленим: закрити сокет і відпустити ввід.
 *
 * @param expect_fd  діяти, лише якщо поточний телефон — саме цей сокет.
 *                   ⚠️ `-1` («будь-який») лишається можливим, але кожен
 *                   викликач має спершу подумати, чи бачив він той самий
 *                   сокет, який збирається гасити: інакше запізніла подія
 *                   від старого з'єднання гасить щойно під'єднаний телефон.
 *
 * Викликають два різні місця, і жодне не ловить усі випадки поодинці:
 *  - закриття сокета (штатний вихід, перезавантаження сторінки);
 *  - подія Wi-Fi «станція від'єдналась», і то лише коли в мережі більше
 *    нікого не лишилось.
 */
void ws_bridge_client_lost(int expect_fd, bool silence);
