/*
 * TX16S Remote UI — емульований ввід: клавіші, тримери, енкодер, сенсор.
 *
 * Ліцензія: GPLv2 (та сама, що в EdgeTX).
 *
 * Тут живе весь стан вводу і **жодного** рядка про EdgeTX: файл збирається
 * звичайним g++ і перевіряється тестами без пульта й без симулятора. Прив'язка
 * до EdgeTX — окремий файл `input_edgetx.cpp`, у ньому чотири короткі обгортки.
 *
 * --- Головне правило цього файлу ---------------------------------------
 *
 * ⚠️ **Тиша в каналі відпускає все.** Залипла емульована клавіша означає, що
 * пульт натискає щось сам по собі, а людина цього не бачить — екрана немає.
 * Тому «відпущено» не потребує ані пакета, ані живого потоку транспорту: воно
 * настає само, коли INPUT_RELEASE_TIMEOUT_MS минуло без жодного пакета **з
 * тих, що несуть ввід**. PING і REFRESH до них не належать — чому саме, див.
 * нижче.
 *
 * Перевіряє це той самий бік, який ввід читає (задачі EdgeTX). Тобто навіть
 * якщо потік транспорту помер, завис у send() або його зняли — клавіші все
 * одно відпустяться, бо їх відпускає читач, а не той, хто натискав.
 *
 * ⚠️ **Межа цієї гарантії й чим вона закрита.** Сам тайм-аут ловить тишу
 * **всього** каналу. Втрачений поодинокий пакет при живому зв'язку він не
 * ловить: якби загубилось саме «відпущено», а решта трафіку йшла далі,
 * клавіша лишилась би натиснутою скільки завгодно. Протокол прямо припускає
 * такі втрати (docs/03-protocol.md: побита LEN з'їдає до 4096 байтів разом із
 * валідними кадрами, що там лежали).
 *
 * Тому клієнт, який шле ввід, зобов'язаний раз на 250 мс слати **повний стан
 * вводу** — пакет 0x87 INPUT_STATE, рівень, а не перехід. `onInputState()`
 * заміщує ним маски утримуваного, і втрачене «відпущено» самолікується за
 * один період. Два числа пов'язані: тайм-аут = чотири пропущені періоди.
 *
 * ⚠️ **Відсувають тайм-аут лише пакети, що несуть ввід** — KEY, ENC, TOUCH,
 * TRIM, INPUT_STATE. PING, REFRESH і невідомі типи його не відсувають, і це
 * не педантизм: на етапі 2 між телефоном і пультом стоїть міст ESP32. Він
 * власний посередник і цілком може слати PING після того, як телефон
 * від'єднався; при правилі «будь-який пакет» клавіша, утримувана в мить
 * розриву Wi-Fi, лишилась би натиснутою назавжди.
 *
 * --- Двоє учасників, без м'ютексів ------------------------------------
 *
 *   потік транспорту   onKey/onTrim/onEncoder/onTouch   пише стан
 *   задачі EdgeTX      takeKeys/takeTrims/…/popTouch    читає й споживає
 *
 * Читач працює у двох різних задачах EdgeTX (клавіші — 10-мілісекундна задача,
 * сенсор і енкодер — LVGL у menusTask), але їхні частини стану не
 * перетинаються, тож між собою вони не конкурують.
 *
 * --- Чому клавіші зі «засувкою» ----------------------------------------
 *
 * `keysPollingCycle()` читає клавіші раз на 10 мс. Клієнт може встигнути
 * прислати «натиснуто» і «відпущено» між двома читаннями — і натискання
 * пропало б безслідно. Тому кожне натискання ще й защіпається: читач
 * обов'язково побачить його рівно один раз, навіть якщо клавішу вже відпустили.
 *
 * --- Чому в енкодера накопичувач, а не різниця -------------------------
 *
 * Гачок 7 додає наше значення до положення фізичного енкодера, а EdgeTX
 * рахує різницю з попереднім читанням і сам запам'ятовує суму. Віддавши раз
 * «+3» і потім нуль, ми отримали б наступним читанням «-3» — тобто фантомний
 * оберт назад. Тому назовні йде **накопичена** позиція, яка ніколи не
 * зменшується сама і не обнуляється при розриві.
 */

#pragma once

#include <stddef.h>
#include <stdint.h>

#include <atomic>

namespace remote_ui {

// Як часто клієнт зобов'язаний повторювати повний стан вводу (0x87).
//
// Це вимога протоколу до клієнта, а не його справа: 250 мс проти 1000 мс
// тайм-ауту дають запас на три пропущені пакети поспіль. Ціна — 80 Б/с у
// зворотному напрямку, який і без того майже порожній.
constexpr uint32_t INPUT_STATE_PERIOD_MS = 250;

// Скільки тиші в каналі означає «клієнта більше немає».
//
// 1000 мс — це чотири пропущені INPUT_STATE поспіль. Менше — і випадкова
// затримка відпускала б клавішу під людиною; більше — і залипла клавіша
// встигла б накрутити автоповтором.
//
// ⚠️ Два числа пов'язані й міняються тільки разом — звідси static_assert.
constexpr uint32_t INPUT_RELEASE_TIMEOUT_MS = 1000;

static_assert(INPUT_RELEASE_TIMEOUT_MS == INPUT_STATE_PERIOD_MS * 4,
              "поріг відпускання = чотири пропущені періоди INPUT_STATE");

// Довжина корисного вантажу 0x87 INPUT_STATE (docs/03-protocol.md):
// 4 маски клавіш + 4 маски тримерів + 1 прапорці + 2 x + 2 y.
//
// Коротший пакет не застосовується взагалі; довший застосовується по перші
// INPUT_STATE_PAYLOAD_SIZE байтів — нові поля протокол дозволяє додавати
// тільки в кінець.
constexpr size_t INPUT_STATE_PAYLOAD_SIZE = 13;

// Скільки часу приписувати клацанню енкодера, перед яким була пауза (або яке
// взагалі перше). Йде в лічильник, з якого EdgeTX рахує прискорення: 500 мс
// дають нульове прискорення, тобто перше клацання після паузи завжди чисте.
constexpr uint32_t ENCODER_DT_IDLE_MS = 500;

// Скільки переходів сенсора (натиск/відпускання) зберігається до читання.
//
// Рухи (MOVE) сюди не потрапляють — вони лише оновлюють поточну точку, тому
// переповнити історію потоком рухів неможливо. Переходів людина робить
// одиниці на секунду, а читач ходить сюди щоразу, коли LVGL опитує сенсор.
constexpr uint32_t TOUCH_HISTORY = 8;

// Події сенсора з протоколу (docs/03-protocol.md, пакет 0x83 TOUCH).
enum TouchEventKind : uint8_t {
  TOUCH_EVENT_DOWN = 0,
  TOUCH_EVENT_MOVE = 1,
  TOUCH_EVENT_UP = 2,
};

// Клавіш у EnumKeys EdgeTX менше за 32; маска клавіш у HELLO теж 32-бітова.
// Усе, що не влазить у маску, відкидається на вході.
constexpr uint8_t INPUT_MAX_BITS = 32;

class InputState
{
 public:
  // --- Бік клієнта: викликає потік транспорту ---------------------------
  //
  // nowMs — монотонний час у мілісекундах; будь-який виклик означає «клієнт
  // живий» і відсуває тайм-аут відпускання.

  // Клавіша з EnumKeys. Код поза межами маски мовчки відкидається: правило
  // сумісності забороняє валитись на тому, чого ми не розуміємо.
  void onKey(uint8_t key, bool pressed, uint32_t nowMs);

  // Тример: індекс — це номер **напрямку** (0..2*кількість тримерів-1), як у
  // EdgeTX (`trim_keys`), а не номер тримера.
  void onTrim(uint8_t index, bool pressed, uint32_t nowMs);

  // Клацання енкодера, зазвичай ±1.
  void onEncoder(int8_t steps, uint32_t nowMs);

  // Подія сенсора; координати обрізаються по екрану.
  void onTouch(uint8_t event, int16_t x, int16_t y, uint32_t nowMs);

  // Повний стан вводу (пакет 0x87) — **рівень, а не перехід**. Заміщує маски
  // утримуваного й тим лікує втрачене «відпущено».
  //
  // Три речі, які тут відбуваються не так, як здається:
  //   - защіпнуті натискання пакет **не чіпає**: засувку гасить лише читач,
  //     інакше повтор стану з'їв би коротке натискання цілком;
  //   - дотик застосовується **тільки переходом**: рівень «пальця немає» при
  //     внутрішньому стані «унизу» дописує відпускання в чергу, а не стирає
  //     непрочитаний натиск;
  //   - енкодер у пакеті відсутній і тут не чіпається взагалі.
  // Повний перелік правил — docs/03-protocol.md, розділ 0x87.
  void onInputState(uint32_t keys, uint32_t trims, bool touchDown, int16_t x,
                    int16_t y, uint32_t nowMs);

  // Розрив зв'язку. Відпускає все негайно, не чекаючи тайм-ауту.
  void onDisconnect();

  // --- Бік EdgeTX: викликають задачі пульта ------------------------------

  // Маска натиснутих клавіш. Защіпнуті натискання віддаються рівно один раз.
  uint32_t takeKeys(uint32_t nowMs);

  // Те саме для тримерів.
  uint32_t takeTrims(uint32_t nowMs);

  // Накопичена позиція енкодера (див. пояснення вгорі файлу).
  int32_t encoderOffset() const;

  // Скільки мілісекунд «пройшло» на віддаленому енкодері з минулого читання:
  // сума проміжків між клацаннями, які прийшли відтоді. Читання **споживає**
  // значення, тому кожен проміжок віддається рівно один раз.
  //
  // Навіщо це взагалі. EdgeTX рахує прискорення ручки з часу між клацаннями
  // (`rotencDt` у rotary_encoder_driver.cpp). Наш шлях цього лічильника не
  // рухав, тобто dt завжди виходило нульовим, EdgeTX вважав, що ручку крутять
  // нескінченно швидко, і прискорення застигало на максимумі: з другого
  // клацання підряд крок стрибав на кілька десятків. Гачок 7 додає це число
  // до лічильника EdgeTX — і прискорення стає таким самим, як у фізичної ручки.
  uint32_t takeEncoderDtMs();

  // Наступний стан сенсора. Повертає false, коли віддаленого дотику немає —
  // тоді драйвер читає фізичний сенсор, як завжди.
  //
  // Поки дотик триває, повертає true на **кожен** виклик: LVGL має бачити
  // натиск усі опитування підряд, інакше довге натискання й перетягування
  // розсипалися б на окремі кліки.
  bool popTouch(int16_t& x, int16_t& y, bool& pressed, uint32_t nowMs);

  // --- Спільне ----------------------------------------------------------

  // true, якщо клієнта немає або він мовчить понад тайм-аут.
  bool linkLost(uint32_t nowMs) const;

  // Повний скид. Потрібен тестам; у прошивці не викликається.
  void reset();

 private:
  // Позначка «клієнт живий», яка й тримає ввід натиснутим.
  //
  // ⚠️ Приватна навмисно. Її ставлять **тільки** обробники пакетів, що несуть
  // ввід; PING, REFRESH і невідомі типи тайм-аут не відсувають (пояснення
  // вгорі файлу). Публічний метод «просто підтвердити життя» повернув би ту
  // саму діру, з якої почалась задача 0008.
  void markAlive(uint32_t nowMs);

  // Спільна частина takeKeys/takeTrims: віддає «натиснуті зараз» разом із
  // защіпнутими й гасить засувку.
  static uint32_t takeMask(std::atomic<uint32_t>& held,
                           std::atomic<uint32_t>& latched, bool lost);

  // Дописує перехід сенсора в кільце. Виносити його окремо варто саме тому,
  // що порядок двох записів усередині — не деталь реалізації, а умова, без
  // якої читач бере ще не заповнену комірку.
  void pushTouchTransition(int16_t x, int16_t y, bool pressed);

  // ⚠️ Викликається писарем, коли той **перший** побачив тишу понад тайм-аут.
  //
  // Скинути самий лише producerDown тут недостатньо, і це головна пастка
  // всього файлу. Тайм-аут помічають двоє незалежно — писар і читач, — і
  // писар, оновивши позначку життя, тишу для читача стирає. Якби він лишив по
  // собі тільки скинутий прапорець, вийшов би глухий кут: переходу в кільці
  // немає, тиші вже немає, і читач віддавав би «натиснуто» вічно, заступаючи
  // фізичний сенсор.
  //
  // Тому писар лишає той самий слід, що й onDisconnect(): нову епоху й межу
  // «усе до сюди — чуже». Читач піде гілкою «епоха змінилась», віддасть
  // відпускання і лише після нього гратиме нові переходи.
  //
  // Викликати обов'язково **до** запису нових переходів у кільце — інакше
  // межа відріже й їх.
  void resyncAfterTimeout();

  // Стан сенсора в одному слові: x:15 | y:15 | натиснуто:1. Чому не структура
  // з трьох полів — див. onTouch у input.cpp.
  static uint32_t packSample(int16_t x, int16_t y, bool pressed);
  static void unpackSample(uint32_t word, int16_t& x, int16_t& y,
                           bool& pressed);

  // --- Пише транспорт, читає EdgeTX ---
  std::atomic<uint32_t> keysHeld{0};
  std::atomic<uint32_t> keysLatched{0};
  std::atomic<uint32_t> trimsHeld{0};
  std::atomic<uint32_t> trimsLatched{0};
  std::atomic<int32_t> encAccum{0};

  // Проміжки між клацаннями віддаленого енкодера, ще не забрані читачем.
  std::atomic<uint32_t> encDtPending{0};

  std::atomic<bool> linkActive{false};
  std::atomic<uint32_t> lastPacketMs{0};

  // Номер з'єднання і лічильник переходів на момент розриву. Потрібні для
  // випадку, коли новий клієнт устиг під'єднатись раніше, ніж LVGL опитав
  // сенсор: без них читач програв би дотик попереднього клієнта як свій.
  std::atomic<uint32_t> linkEpoch{0};
  std::atomic<uint32_t> linkDropSeq{0};

  // Сенсор: поточна точка (та сама розкладка, що й у кільці) і лічильник
  // переходів. Пакування в одне слово рятує від напівоновленої координати:
  // читач не має побачити нове x зі старим y.
  std::atomic<uint32_t> touchPoint{0};
  std::atomic<uint32_t> touchSeq{0};
  std::atomic<uint32_t> history[TOUCH_HISTORY]{};

  // --- Тільки потік транспорту ---
  bool producerDown{false};

  // Час попереднього клацання енкодера — з нього рахується проміжок. Окремий
  // прапорець, а не «нуль означає не було»: нуль — цілком законна позначка
  // часу, а лічильник мілісекунд EdgeTX проходить через нього раз на 49 днів.
  uint32_t lastEncoderMs{0};
  bool hasLastEncoder{false};

  // --- Тільки задача LVGL ---
  uint32_t touchEpoch{0};
  uint32_t touchTaken{0};
  bool consumerDown{false};
  int16_t consumerX{0};
  int16_t consumerY{0};
};

// Єдиний примірник стану. Статичний, без динамічної пам'яті.
InputState& inputState();

// --- Пакет клієнта -> стан вводу --------------------------------------------

// Розбирає пакет, що несе ввід, і застосовує його до стану.
//
// Повертає true, якщо тип пакета — «ввід» і його зрозуміли. На false транспорт
// розбирається з пакетом сам (REFRESH перемальовує екран, PING відповідає
// HELLO, невідомі типи мовчки відкидаються — правило сумісності).
//
// ⚠️ Позначку життя ставить **тільки** цей розбір і тільки на true. Тому
// PING, REFRESH і невідомі типи тайм-аут не відсувають — див. пояснення вгорі
// файлу.
//
// Живе тут, а не в транспорті, бо це та сама логіка для TCP у симуляторі, для
// UART на пульті й для моста ESP32 — і бо інакше її не перевірити тестами без
// сокета.
bool applyInputPacket(InputState& input, uint8_t type, const uint8_t* payload,
                      size_t length, uint32_t nowMs);

}  // namespace remote_ui
