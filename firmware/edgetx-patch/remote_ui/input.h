/*
 * TX16S Remote UI — емульований ввід: клавіші, тримери, енкодер, сенсор.
 *
 * Ліцензія: GPLv2 (та сама, що в EdgeTX).
 *
 * Тут живе весь стан вводу і **жодного** рядка про EdgeTX: файл збирається
 * звичайним g++ і перевіряється тестами без пульта й без симулятора. Прив'язка
 * до EdgeTX — окремий файл `input_edgetx.cpp`, у ньому чотири короткі обгортки.
 *
 * --- Головне правило цього файлу ---------------------------------------
 *
 * ⚠️ **Тиша в каналі відпускає все.** Залипла емульована клавіша означає, що
 * пульт натискає щось сам по собі, а людина цього не бачить — екрана немає.
 * Тому «відпущено» не потребує ані пакета, ані живого потоку транспорту: воно
 * настає само, коли INPUT_RELEASE_TIMEOUT_MS минуло без жодного пакета.
 *
 * Перевіряє це той самий бік, який ввід читає (задачі EdgeTX). Тобто навіть
 * якщо потік транспорту помер, завис у send() або його зняли — клавіші все
 * одно відпустяться, бо їх відпускає читач, а не той, хто натискав.
 *
 * ⚠️ **Межа цієї гарантії, і вона реальна.** Тайм-аут ловить тишу **всього**
 * каналу. Він не ловить втрачений поодинокий пакет при живому зв'язку: якщо
 * загубиться саме «відпущено», а PING ітимуть далі, клавіша лишиться
 * натиснутою скільки завгодно. Протокол прямо припускає такі втрати
 * (docs/03-protocol.md: побита LEN з'їдає до 4096 байтів разом із валідними
 * кадрами, що там лежали).
 *
 * Закрити це може лише періодичний повтор **повного стану вводу** з боку
 * клієнта — маски утримуваних клавіш і стану дотику, а не самих переходів.
 * Це зміна протоколу, і вона за асистентом (питання підняте в задачі 0007).
 *
 * --- Двоє учасників, без м'ютексів ------------------------------------
 *
 *   потік транспорту   onKey/onTrim/onEncoder/onTouch   пише стан
 *   задачі EdgeTX      takeKeys/takeTrims/…/popTouch    читає й споживає
 *
 * Читач працює у двох різних задачах EdgeTX (клавіші — 10-мілісекундна задача,
 * сенсор і енкодер — LVGL у menusTask), але їхні частини стану не
 * перетинаються, тож між собою вони не конкурують.
 *
 * --- Чому клавіші зі «засувкою» ----------------------------------------
 *
 * `keysPollingCycle()` читає клавіші раз на 10 мс. Клієнт може встигнути
 * прислати «натиснуто» і «відпущено» між двома читаннями — і натискання
 * пропало б безслідно. Тому кожне натискання ще й защіпається: читач
 * обов'язково побачить його рівно один раз, навіть якщо клавішу вже відпустили.
 *
 * --- Чому в енкодера накопичувач, а не різниця -------------------------
 *
 * Гачок 7 додає наше значення до положення фізичного енкодера, а EdgeTX
 * рахує різницю з попереднім читанням і сам запам'ятовує суму. Віддавши раз
 * «+3» і потім нуль, ми отримали б наступним читанням «-3» — тобто фантомний
 * оберт назад. Тому назовні йде **накопичена** позиція, яка ніколи не
 * зменшується сама і не обнуляється при розриві.
 */

#pragma once

#include <stdint.h>

#include <atomic>

namespace remote_ui {

// Скільки тиші в каналі означає «клієнта більше немає».
//
// 1000 мс — це чотири пропущені PING поспіль. Менше — і випадкова затримка
// відпускала б клавішу під людиною; більше — і залипла клавіша встигла б
// накрутити автоповтором. Зворотний бік каналу (клієнт -> пульт) майже
// порожній: пакети вводу й PING разом не дають і сотні байтів на секунду.
//
// ⚠️ Число тримається на періодичності PING, а вона тепер вимога протоколу, а
// не справа клієнта: клієнт, який шле PING рідше за 250 мс, отримає розтиснуту
// під пальцем клавішу. Специфікація (docs/03-protocol.md) поки каже «раз на
// 2 с» — розбіжність винесена в результат задачі 0007, правити її асистентові.
constexpr uint32_t INPUT_RELEASE_TIMEOUT_MS = 1000;

// Скільки переходів сенсора (натиск/відпускання) зберігається до читання.
//
// Рухи (MOVE) сюди не потрапляють — вони лише оновлюють поточну точку, тому
// переповнити історію потоком рухів неможливо. Переходів людина робить
// одиниці на секунду, а читач ходить сюди щоразу, коли LVGL опитує сенсор.
constexpr uint32_t TOUCH_HISTORY = 8;

// Події сенсора з протоколу (docs/03-protocol.md, пакет 0x83 TOUCH).
enum TouchEventKind : uint8_t {
  TOUCH_EVENT_DOWN = 0,
  TOUCH_EVENT_MOVE = 1,
  TOUCH_EVENT_UP = 2,
};

// Клавіш у EnumKeys EdgeTX менше за 32; маска клавіш у HELLO теж 32-бітова.
// Усе, що не влазить у маску, відкидається на вході.
constexpr uint8_t INPUT_MAX_BITS = 32;

class InputState
{
 public:
  // --- Бік клієнта: викликає потік транспорту ---------------------------
  //
  // nowMs — монотонний час у мілісекундах; будь-який виклик означає «клієнт
  // живий» і відсуває тайм-аут відпускання.

  // Клавіша з EnumKeys. Код поза межами маски мовчки відкидається: правило
  // сумісності забороняє валитись на тому, чого ми не розуміємо.
  void onKey(uint8_t key, bool pressed, uint32_t nowMs);

  // Тример: індекс — це номер **напрямку** (0..2*кількість тримерів-1), як у
  // EdgeTX (`trim_keys`), а не номер тримера.
  void onTrim(uint8_t index, bool pressed, uint32_t nowMs);

  // Клацання енкодера, зазвичай ±1.
  void onEncoder(int8_t steps, uint32_t nowMs);

  // Подія сенсора; координати обрізаються по екрану.
  void onTouch(uint8_t event, int16_t x, int16_t y, uint32_t nowMs);

  // Будь-який інший пакет (PING, REFRESH): вводу не змінює, але доводить, що
  // клієнт живий.
  void onAnyPacket(uint32_t nowMs);

  // Розрив зв'язку. Відпускає все негайно, не чекаючи тайм-ауту.
  void onDisconnect();

  // --- Бік EdgeTX: викликають задачі пульта ------------------------------

  // Маска натиснутих клавіш. Защіпнуті натискання віддаються рівно один раз.
  uint32_t takeKeys(uint32_t nowMs);

  // Те саме для тримерів.
  uint32_t takeTrims(uint32_t nowMs);

  // Накопичена позиція енкодера (див. пояснення вгорі файлу).
  int32_t encoderOffset() const;

  // Наступний стан сенсора. Повертає false, коли віддаленого дотику немає —
  // тоді драйвер читає фізичний сенсор, як завжди.
  //
  // Поки дотик триває, повертає true на **кожен** виклик: LVGL має бачити
  // натиск усі опитування підряд, інакше довге натискання й перетягування
  // розсипалися б на окремі кліки.
  bool popTouch(int16_t& x, int16_t& y, bool& pressed, uint32_t nowMs);

  // --- Спільне ----------------------------------------------------------

  // true, якщо клієнта немає або він мовчить понад тайм-аут.
  bool linkLost(uint32_t nowMs) const;

  // Повний скид. Потрібен тестам; у прошивці не викликається.
  void reset();

 private:
  // Спільна частина takeKeys/takeTrims: віддає «натиснуті зараз» разом із
  // защіпнутими й гасить засувку.
  static uint32_t takeMask(std::atomic<uint32_t>& held,
                           std::atomic<uint32_t>& latched, bool lost);

  // Стан сенсора в одному слові: x:15 | y:15 | натиснуто:1. Чому не структура
  // з трьох полів — див. onTouch у input.cpp.
  static uint32_t packSample(int16_t x, int16_t y, bool pressed);
  static void unpackSample(uint32_t word, int16_t& x, int16_t& y,
                           bool& pressed);

  // --- Пише транспорт, читає EdgeTX ---
  std::atomic<uint32_t> keysHeld{0};
  std::atomic<uint32_t> keysLatched{0};
  std::atomic<uint32_t> trimsHeld{0};
  std::atomic<uint32_t> trimsLatched{0};
  std::atomic<int32_t> encAccum{0};

  std::atomic<bool> linkActive{false};
  std::atomic<uint32_t> lastPacketMs{0};

  // Номер з'єднання і лічильник переходів на момент розриву. Потрібні для
  // випадку, коли новий клієнт устиг під'єднатись раніше, ніж LVGL опитав
  // сенсор: без них читач програв би дотик попереднього клієнта як свій.
  std::atomic<uint32_t> linkEpoch{0};
  std::atomic<uint32_t> linkDropSeq{0};

  // Сенсор: поточна точка (та сама розкладка, що й у кільці) і лічильник
  // переходів. Пакування в одне слово рятує від напівоновленої координати:
  // читач не має побачити нове x зі старим y.
  std::atomic<uint32_t> touchPoint{0};
  std::atomic<uint32_t> touchSeq{0};
  std::atomic<uint32_t> history[TOUCH_HISTORY]{};

  // --- Тільки потік транспорту ---
  bool producerDown{false};

  // --- Тільки задача LVGL ---
  uint32_t touchEpoch{0};
  uint32_t touchTaken{0};
  bool consumerDown{false};
  int16_t consumerX{0};
  int16_t consumerY{0};
};

// Єдиний примірник стану. Статичний, без динамічної пам'яті.
InputState& inputState();

}  // namespace remote_ui
