// --- Числа ------------------------------------------------------------------

// Період проходу транспорту.
//
// 2 мс обрано з двох боків. Знизу: найбільший буфер передачі (4103 байти) на
// 921600 бод іде ~44.5 мс (при 8N1 на дроті десять біт на байт, а не вісім),
// тож 2 мс — це ~4% простою каналу між пачками, а не 30%, як було б із
// періодом 20 мс. Зверху: приймальна черга драйвера — 512 байтів, тобто 5.5 мс
// потоку на цій швидкості; опитувати рідше означало б ризикувати
// переповненням.
//
// ⚠️ Скільки триває сам прохід. Порожній — одиниці мікросекунд. Найдорожчий —
// одиниці **мілісекунд**, і трапляється він не в екзотиці, а на кожному
// REFRESH: однотонна плитка стискається в 31 байт разом із кадруванням, тож у
// пачку влазить близько 130 плиток, і це 130 копіювань по 2 КБ із SDRAM плюс
// побітовий CRC по всіх 4103 байтах. Ці кілька мілісекунд ніхто не читає
// приймальну чергу — запасу в 5.5 мс вистачає, але він не безмежний. Клієнт
// шле близько 80 байтів на секунду, тобто в нормі черга майже порожня.
constexpr uint32_t POLL_PERIOD_MS = 2;

// Період, коли порт узагалі не наш (режим перемкнули). Прокидатись часто нема
// навіщо, але задача лишається живою: режим можуть повернути.
constexpr uint32_t IDLE_PERIOD_MS = 20;

// Скид декодувальника за тишею в каналі. Шар кадрування часу не має
// (docs/03-protocol.md), тому обірваний посеред кадру потік розсинхронізував би
// приймач назавжди — доки транспорт не скине його сам.
//
// Те саме число, що в transport_simu.cpp і в tools/remote_ui_proto.py: воно
// про протокол, а не про трубу.
constexpr uint32_t SILENCE_RESET_MS = 100;

// Скільки мовчання означає «клієнта більше немає».
//
// Клієнт зобов'язаний слати повний стан вводу раз на 250 мс і PING раз на 2 с,
// тому 3 с тиші — це вже не пауза. Після цього ми перестаємо передавати: на
// столі це виглядає як «висмикнули міст — пульт затих», а не як задача, що
// вічно жене плитки в нікуди.
//
// Ввід це відпустити не встигає й не мусить: за нього відповідає власний
// тайм-аут читача (1000 мс, input.h), і він спрацює раніше.
constexpr uint32_t CLIENT_TIMEOUT_MS = 3000;

// Стек задачі, у словах. Прохід не рекурсивний і великих локальних змінних не
// має: усі буфери статичні. 512 слів (2 КБ) — це запас у кілька разів.
constexpr unsigned TASK_STACK_WORDS = 512;

// Пріоритет: рівно на щабель вище за menusTask.
constexpr unsigned TASK_PRIO = MENUS_TASK_PRIO + 1;

// Головна умова вибору контексту, записана так, щоб її не можна було мовчки
// порушити при перебазуванні на новий EdgeTX.
static_assert(TASK_PRIO > MENUS_TASK_PRIO,
              "транспорт має витісняти малювання, інакше кадри йтимуть ривками");
// Обидві перевірки тримаються на гілці `FREE_RTOS` у `tasks.h`: у другій гілці
// `AUDIO_TASK_PRIO` дорівнює 2 і ця перевірка не пройшла б. Сьогодні це
// нешкідливо, бо друга гілка — це симулятор, а файл під `SIMU` не збирається
// взагалі. Але знати варто: якщо upstream колись зведе гілки, тут упаде збірка,
// а не поведінка на льоту.
static_assert(TASK_PRIO < AUDIO_TASK_PRIO,
              "транспорт не сміє заважати ані звуку, ані мікшеру");

// Режим порту зберігається в чотирьох бітах на порт (`SERIAL_CONF_MODE_MASK`).
// Поки їх вистачає — все гаразд; коли upstream додасть режимів понад 15, наш
// номер мовчки обрізався б до чужого, і налаштування «Remote UI» одного дня
// стало б, скажімо, «GPS».
static_assert(UART_MODE_REMOTE_UI <= SERIAL_CONF_MODE_MASK,
              "номер режиму не влазить у поле налаштувань порту");

// --- Пам'ять ----------------------------------------------------------------

// ⚠️ Буфер передачі. `__DMA` тут обов'язковий — без нього прямий доступ до
// пам'яті мовчки вимкнеться (пояснення на початку файлу).
//
// Розмір — найбільший кадр протоколу. Так гарантовано, що **будь-який**
