void remoteUiSetSerialDriver(void* ctx, const etx_serial_driver_t* drv,
                             const etx_serial_port_t* port)
{
  using namespace remote_ui;

  if (ctx == nullptr) {
    // ⚠️ Від'єднання — але не обов'язково **наше**. EdgeTX викликає цей гачок
    // для кожного порту, чий режим — наш, тож рядок `mode: REMOTE_UI`, вписаний
    // наосліп під другий порт, приходив би сюди теж. Опустити ворота на такий
    // виклик означало б тихо вбити робочий AUX1 — без жодної ознаки для людини,
    // у якої немає екрана.
    //
    // Тому гасимо себе лише тоді, коли гасять саме той порт, на якому ми
    // працюємо. `port == nullptr` (шлях `serialStop()`) своїм не вважаємо: у
    // цьому дереві `serialStop()` викликається тільки для VCP, а на VCP ми не
    // працюємо ніколи.
    if (port != nullptr && port == s_port) {
      s_linkUp.store(false, std::memory_order_release);
      s_port = nullptr;
      inputState().onDisconnect();
    }
    return;
  }

  if (!driverUsable(drv) || !portUsable(port)) {
    // Наш режим спробували ввімкнути на порту або драйвері, яких ми не вміємо.
    // Воріт не чіпаємо з тієї самої причини: на правильному порту транспорт
    // може працювати законно, і одруківка в radio.yml не має його вбивати.
    return;
  }

  // Ворота опускаються **перед** записом вказівників: інакше задача могла б
  // побачити напівоновлену пару «драйвер + контекст».
  s_linkUp.store(false, std::memory_order_release);

  s_ctx = ctx;
  s_drv = drv;
  s_port = port;

  s_restart.store(true, std::memory_order_relaxed);
  s_linkUp.store(true, std::memory_order_release);

  if (!s_taskStarted) {
    task_create(&s_task, transportTask, "remoteui", s_taskStack,
                TASK_STACK_WORDS, TASK_PRIO);
    s_taskStarted = true;
  }
}

