// Драйвер, який ми вміємо крутити.
//
// Перевірка не формальна: у VCP (`usbd_cdc.cpp`) `sendBuffer` — nullptr,
// `getByte` — nullptr, а `usbSerialPutc()` при переповненні свого кільця
// **мовчки затирає** те, що там лежало. Тобто на VCP цей код видавав би
// зіпсовані кадри. Краще не робити нічого, ніж робити це.
bool driverUsable(const etx_serial_driver_t* drv)
{
  return drv != nullptr && drv->sendBuffer != nullptr &&
         drv->txCompleted != nullptr && drv->getByte != nullptr;
}

// ⚠️ Порт, який ми вміємо крутити. Ця перевірка потрібна саме тому, що
// існує гачок 4, а не попри нього.
//
// `isSerialModeAvailable()` — фільтр **меню**, і викликає його тільки меню.
// `initSerialPorts()` бере режим прямо з `g_eeGeneral.serialPort`, тобто з
// `radio.yml`, без жодної перевірки. А головне обмеження цього проєкту в тому,
// що `radio.yml` тут правлять **наосліп**: рядок `mode: REMOTE_UI` під `AUX2`
// доїхав би сюди без перешкод.
//
// Чим це погано конкретно: AUX1 і AUX2 користуються тим самим
// `STM32SerialDriver`, тож `driverUsable()` пропустив би обидва. Але в AUX2
// `.txDMA = nullptr` (`boards/generic_stm32/aux_ports.cpp`), і
// `stm32_serial_send_buffer()` пішов би запасним шляхом «по байту через чергу
// на 512 байтів», яка при переповненні **мовчки викидає** решту. Наша пачка —
// до 4103 байтів. Клієнт бачив би суцільні помилки CRC, а полагодити через
// меню було б неможливо: екрана немає.
//
// Умова дослівно повторює гачок 4 (docs/05-hooks.md, пункт 4), і це свідоме
// дублювання: там воно ховає режим від людини, тут — від файлу. Міняти
// обидва місця треба разом, про що в документі сказано.
bool portUsable(const etx_serial_port_t* port)
{
#if defined(AUX_SERIAL_DMA_TX)
  return port != nullptr && port == serialGetPort(SP_AUX1);
#else
  // На цій цілі прямого доступу до пам'яті на передачу немає ніде.
  (void)port;
  return false;
#endif
}

void endSession()
{
  // Клієнта більше немає — усе, що він тримав натиснутим, відпускається.
  // Тайм-аут читача лишається другим рубежем: він спрацює навіть тоді, коли
  // ця задача загине й сюди не дійде.
  inputState().onDisconnect();

  s_clientSeen = false;
  s_helloPending = false;
  s_refreshDeferred = false;
  s_tilesSinceFrameEnd = 0;
  s_txUsed = 0;
  s_decoder.reset();
}

void beginSession()
{
  endSession();

  const uint32_t now = nowMs();
  s_lastByteMs = now;
  s_lastPacketMs = now;

  // Лічильник кадрів беремо як є, а не «мінус один»: над послідовним портом
  // ніхто нам ще не сказав «покажи екран», і слати FRAME_END у порожнечу
  // немає сенсу. Повний екран приїде на REFRESH, як велить протокол.
  s_lastFrameSent = captureFrameCount();
}

inline bool linkUp() { return s_linkUp.load(std::memory_order_acquire); }

// --- Приймання --------------------------------------------------------------

void onPacket(uint8_t type, const uint8_t* payload, size_t length, void* context)
{
  (void)context;

  const uint32_t now = nowMs();

  // Перший валідний пакет — це і є «клієнт з'явився». Іншої ознаки над
  // послідовним портом не існує.
  if (!s_clientSeen) {
    s_clientSeen = true;
    s_lastFrameSent = captureFrameCount();
  }
  s_lastPacketMs = now;

  // ⚠️ Позначку «клієнт живий» для тайм-ауту вводу ставлять **тільки** пакети,
  // що несуть ввід, і ставить її сам розбір усередині applyInputPacket.
  // PING, REFRESH і невідомі типи його не відсувають — на етапі 2 між
  // телефоном і пультом стоїть міст ESP32, який власний посередник і цілком
  // може слати PING після того, як телефон від'єднався.
  //
  // `s_lastPacketMs` вище — інша річ: це присутність **труби**, а не вводу.
  if (applyInputPacket(inputState(), type, payload, length, now)) {
    return;
  }

  switch (type) {
    case PKT_REFRESH:
      // Кадр закриється FRAME_END сам, коли всі позначені плитки поїдуть, —
      // за правилом «карта спорожніла» у transmit(). Прапорця «прийшов REFRESH»
      // тут немає навмисно: він закривав би кадр **першою** пачкою, тобто
      // раніше за плитки, які мав закрити.
      //
      // Відмова буває одна: тіньового кадру ще немає. Тоді запит відкладається,
      // а не зникає.
      if (!captureMarkAllDirty()) {
        s_refreshDeferred = true;
      }
      break;

    case PKT_PING:
      // Відповідь складається у фазі передачі, а не тут: буфер може бути під
      // прямим доступом до пам'яті, і чекати на нього ми не маємо права.
      s_helloPending = true;
      break;

    // Невідомий тип — мовчки повз, як вимагає правило сумісності. Сюди ж
    // потрапляє й пакет вводу з обрізаним вантажем: applyInputPacket відмовив,
    // а робити з ним більше нема чого.
    default:
      break;
  }
}

void receive()
{
  // Читаємо побайтово, а не через `copyRxBuffer()`, і це свідомо. Клієнт шле
  // одиниці пакетів на секунду — сотню-другу байтів, — тож виграш від пакетного
  // читання нульовий, а другий шлях у коді довелося б перевіряти на пульті,
  // якого ще ніхто не вмикав. Один шлях, який точно працює, кращий за два.
  //
  // Стеля циклу — на випадок, якщо з того боку хтось безперервно ллє байти:
  // прохід має закінчуватись завжди.
  constexpr int MAX_BYTES_PER_PASS = 1024;
  constexpr size_t CHUNK = 64;

  uint8_t chunk[CHUNK];
  size_t filled = 0;
  int total = 0;

  const auto getByte = s_drv->getByte;

  uint8_t byte;
  while (total < MAX_BYTES_PER_PASS && getByte(s_ctx, &byte) > 0) {
    chunk[filled++] = byte;
    ++total;

    if (filled == CHUNK) {
      s_decoder.feed(chunk, filled, onPacket, nullptr);
      filled = 0;
    }
  }

  if (filled > 0) {
    s_decoder.feed(chunk, filled, onPacket, nullptr);
  }

  const uint32_t now = nowMs();

  if (total > 0) {
    s_lastByteMs = now;
    return;
  }

  if (now - s_lastByteMs > SILENCE_RESET_MS) {
    // Тиша: якщо декодувальник завис посеред обірваного кадру, звільняємо
    // його. Коли він і так на початку, скид нічого не змінює.
    s_decoder.reset();
    s_lastByteMs = now;
  }
}

// --- Передача ---------------------------------------------------------------

// Дописує кадр у буфер передачі. Повертає false, якщо не влізло, — і це
// звичайний робочий результат, а не помилка.
bool appendFrame(uint8_t type, const uint8_t* payload, size_t payloadLen)
{
  const size_t frameLen = encodeFrame(type, payload, payloadLen,
                                      s_txBuf + s_txUsed,
                                      sizeof(s_txBuf) - s_txUsed);
  if (frameLen == 0) {
    return false;
  }

  s_txUsed += frameLen;
  return true;
}

void transmit()
{
  // ⚠️ Єдине питання про передачу, яке ми ставимо. Ствердна відповідь означає,
  // що буфер вільний; заперечна — що цього проходу не передаємо нічого. Ніяких
  // «зачекаємо, поки звільниться».
  if (!s_drv->txCompleted(s_ctx)) {
    return;
  }

  s_txUsed = 0;

  // Вітання йде першим: інакше пачка плиток могла б відсувати його
  // проходами, а клієнт до HELLO не знає навіть розміру екрана.
  if (s_helloPending) {
    const size_t helloLen = buildHello(s_helloPayload, sizeof(s_helloPayload));
    if (helloLen > 0 && appendFrame(PKT_HELLO, s_helloPayload, helloLen)) {
      s_helloPending = false;
    }
  }

  // Відкладений REFRESH: щойно тіньовий кадр з'явився, застосовуємо його.
  if (s_refreshDeferred && captureMarkAllDirty()) {
    s_refreshDeferred = false;
  }

  // Лічильник кадрів знімається **до** порції плиток: інакше кадр, який
  // завершився вже під час відправлення, порахувався б відправленим, а
  // частина його плиток лишилася б у карті до наступної зміни екрана.
  const uint32_t framesBefore = captureFrameCount();

  // `drained` — чи карта брудних плиток спорожніла саме цим проходом. Це не
  // дрібниця обліку, а половина правила закриття кадру нижче.
  bool drained = false;

  int sentTiles = 0;
  TileRef tile;
  while (sentTiles < TILE_COUNT) {
    if (!captureTakeTile(tile, s_tilePixels, TILE_MAX_PIXELS)) {
      drained = true;
      break;
    }

    const size_t payloadLen =
        encodeTilePayload(tile, s_tilePixels, s_payload, sizeof(s_payload));

    if (payloadLen == 0) {
      // Скласти пакет не вийшло — це не розрив, а наша помилка. Плитку
      // повертаємо в брудні, інакше зміна зникне тихо.
      captureReturnTile(tile);
      break;
    }

    if (!appendFrame(PKT_TILE, s_payload, payloadLen)) {
      // Пачка заповнена. Плитка лишається брудною і піде наступним проходом —
      // це і є вся плавна деградація.
      //
      // Так, її щойно стиснули дарма. Один зайвий RLE на прохід дешевший за
      // спробу вгадати наперед, скільки байтів дасть стиснення.
      captureReturnTile(tile);
      break;
    }

    ++sentTiles;
  }

  // Цикл міг вийти й за лічильником — на цілі, де вся сітка влазить в одну
  // пачку, це рівно шлях REFRESH. Тоді карта вже порожня, але `drained` цього
  // не побачив, і кадр закрився б на прохід пізніше.
  if (!drained && captureDirtyCount() == 0) {
    drained = true;
  }

  s_tilesSinceFrameEnd += static_cast<uint32_t>(sentTiles);

  // ⚠️ Коли закривати кадр. Дві причини, і потрібна будь-яка з них — але
  // тільки якщо від минулого FRAME_END справді щось поїхало.
  //
  // 1. **Карта спорожніла.** Усе, що ми знали про зміни, лежить на дроті —
  //    картинка в клієнта цілісна. Саме ця причина закриває кадр після
  //    REFRESH і після великої перемальовки: вони не влазять у пачку 4103
  //    байти й ідуть десятком проходів.
  //
  //    Тут вузьке місце, на якому легко помилитись: прив'язати закриття до
  //    самого REFRESH означало б закрити кадр **першою** пачкою, тобто
  //    раніше, ніж поїхали плитки, які він мав закрити. Клієнт малює в
  //    позаекранний буфер і показує його лише на FRAME_END — він показав би
  //    десяту частину екрана й тримав решту непоказаною, доки LVGL сам щось
  //    не перемалює. На нерухомому головному екрані це хвилина.
  //
  // 2. **LVGL закрив кадр** (`framesBefore` зрушив). Це причина «в русі»:
  //    поки людина крутить меню, брудні плитки з'являються швидше, ніж
  //    ідуть, карта не порожніє ніколи, і без цієї гілки картинка застигла б
  //    саме тоді, коли має рухатись.
  //
  // 3. **Плиток пішло на цілий екран.** Запобіжник від однієї межі: карта може
  //    не порожніти, а LVGL — не закривати кадрів, якщо клієнт шле REFRESH
  //    частіше, ніж зливається пачка. Міст, що перепитує REFRESH на кожному
  //    тріпотінні Wi-Fi, потрапив би саме туди, і картинка застигла б назовсім.
  //    Коли на дріт поїхав цілий екран плиток, показувати вже безпечно.
  //
  // Не влізло — `s_lastFrameSent` і `s_tilesSinceFrameEnd` лишаються як були,
  // тому наступний прохід спробує знову. Окремого прапорця для цього не
  // потрібно.
  if (s_tilesSinceFrameEnd > 0 &&
      (drained || framesBefore != s_lastFrameSent ||
       s_tilesSinceFrameEnd >= static_cast<uint32_t>(TILE_COUNT))) {
    if (appendFrame(PKT_FRAME_END, nullptr, 0)) {
      s_lastFrameSent = framesBefore;
      s_tilesSinceFrameEnd = 0;
    }
  }

  if (s_txUsed > 0) {
    // Віддаємо буфер прямому доступу до пам'яті й одразу виходимо. Драйвер
    // читатиме з s_txBuf сам; наступного проходу txCompleted() скаже, чи
    // дочитав. До того часу буфер не чіпаємо.
    s_drv->sendBuffer(s_ctx, s_txBuf, static_cast<uint32_t>(s_txUsed));
  }
}

// --- Задача -----------------------------------------------------------------

void transportTask()
{
  while (true) {
    if (!s_linkUp.load(std::memory_order_acquire)) {
      sleep_ms(IDLE_PERIOD_MS);
      continue;
    }

    if (s_restart.exchange(false, std::memory_order_relaxed)) {
      beginSession();
    }

    receive();

    if (s_clientSeen) {
      if (nowMs() - s_lastPacketMs > CLIENT_TIMEOUT_MS) {
        endSession();
      } else {
        transmit();
      }
    }

    // ⚠️ Саме sleep_ms, а не sleep_until. `sleep_until()` при простроченому
    // терміні повертається негайно й не поступається процесором — прохід, що
    // затягнувся, перетворив би задачу на цикл без пауз, а ми вище за
    // menusTask. sleep_ms поступається завжди.
    sleep_ms(POLL_PERIOD_MS);
  }
}

