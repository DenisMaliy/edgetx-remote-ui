/*
 * TX16S Remote UI — транспорт на залізі: AUX1 через драйвер EdgeTX.
 *
 * Ліцензія: GPLv2 (та сама, що в EdgeTX).
 *
 * Той самий байтовий потік, що в симуляторі йде в TCP (transport_simu.cpp),
 * тут їде в справжній послідовний порт на 921600 бод. Протокол і його межі не
 * змінюються — змінюється лише труба.
 *
 * ============================================================================
 * Три рішення, які тут головні. Решта файлу — подробиці.
 * ============================================================================
 *
 * 1. ⚠️ ХТО ЦЕ КРУТИТЬ: власна задача FreeRTOS, пріоритет 2.
 *
 *    У симуляторі транспорт живе в окремому потоці ОС. На пульті потоків
 *    немає, тому контекст виконання довелося вибирати, і вибір не нейтральний.
 *
 *    Що було на столі:
 *
 *    - **menusTask (пріоритет 1)** — та сама задача, у якій виконується гачок
 *      захоплення. Відпадає: її витісняє мікшер будь-коли, а перемальовка
 *      LVGL займає десятки мілісекунд поспіль. Транспорт, підвішений за
 *      малюванням, дихав би ривками рівно тоді, коли передавати треба
 *      найбільше — у русі. Гірше того: приймання вводу теж стало б заручником
 *      малювання, а це замкнене коло «клієнт натиснув -> пульт малює ->
 *      наступне натискання чекає, доки домалює».
 *
 *    - **службова задача таймерів (пріоритет 2)** — туди ходить `spacemouse`,
 *      і спокуса зробити так само велика: `timer_create()` не потребує ані
 *      стека, ані нового гачка. Відпадає, і причина конкретна: у тій самій
 *      задачі крутиться `per10ms()` (а всередині нього — `keysPollingCycle()`,
 *      тобто наш же гачок 6) і телеметрія раз на 2 мс. Один наш прохід — це до
 *      кількох мілісекунд RLE й CRC (оцінка нижче, біля POLL_PERIOD_MS). Живучи
 *      в тій задачі, ми відсували б опитування клавіш і телеметрію рівно
 *      настільки — цілим проходом, без жодного поділу часу.
 *
 *    - **власна задача, пріоритет `MENUS_TASK_PRIO + 1` = 2** — обрано.
 *      Мікшер (4) і звук (3) витісняють нас завжди, тобто ані радіоканал, ані
 *      звук ми зачепити не можемо за побудовою. Ми витісняємо menusTask (1),
 *      тобто малювання не може заморити транспорт голодом.
 *
 *      Пріоритетів у FreeRTOS тут усього п'ять (`configMAX_PRIORITIES`), і
 *      щабель 2 — єдиний, що лишається між малюванням і звуком.
 *
 *      ⚠️ Чесно про щабель 2: він **не вільний**, на ньому вже сидить та сама
 *      службова задача таймерів. Тобто службову задачу ми все одно затримуємо
 *      — але не на весь свій прохід, як було б, якби ми жили всередині неї, а
 *      максимум на такт планувальника (1 мс): рівні пріоритети діляться часом
 *      (`configUSE_TIME_SLICING` за замовчуванням увімкнено), і задача рівного
 *      пріоритету, що прокинулась, витіснення не викликає. Виграш саме в цьому
 *      послабленні, а не в його відсутності.
 *
 *    Задача створюється з гачка 3, тобто в мить, коли порт справді
 *    налаштували на наш режим. Жодного зайвого гачка це не коштує, а на
 *    пульті, де Remote UI не ввімкнено, задачі просто немає.
 *
 * 2. ⚠️ ТРАНСПОРТ НІКОГО НЕ ЧЕКАЄ.
 *
 *    Ані блокувального запису, ані очікування вільного буфера, ані циклів
 *    «поки не відправиться». `waitForTxCompleted()` у цьому файлі не
 *    викликається жодного разу — і не має.
 *
 *    Замість очікування — питання `txCompleted()` на початку передачі:
 *
 *      прямий доступ до пам'яті ще жує буфер -> цього проходу не передаємо
 *      нічого, плитки лишаються брудними й підуть наступним проходом.
 *
 *    Те саме всередині проходу: плитка, яка не влізла в залишок буфера,
 *    повертається в брудні через `captureReturnTile()`. Це та сама плавна
 *    деградація, що описана в docs/02-architecture.md: кадри рідшають, але
 *    кожен показаний кадр цілісний.
 *
 *    Причина сувора: ми на пріоритеті 2. Задача, що чекає на 921600 бод,
 *    чекала б до 45 мс на кадр — і всі ці 45 мс не працювала б menusTask.
 *
 * 3. ⚠️ БУФЕР ПЕРЕДАЧІ МУСИТЬ ЛЕЖАТИ В `.ram`, ІНАКШЕ DMA ТИХО ВИМКНЕТЬСЯ.
 *
 *    `stm32_serial_send_buffer()` бере прямий доступ до пам'яті лише тоді,
 *    коли буфер проходить `_IS_DMA_BUFFER()` і вирівняний на 4. На STM32F4 ця
 *    перевірка — це «адреса між `_sram` і `_eram`», тобто **всередині секції
 *    `.ram`**. Звичайний `.bss` її не проходить, а `.data` на цій цілі взагалі
 *    лежить у CCM, куди прямий доступ до пам'яті не дістає.
 *
 *    Не пройшли перевірку — драйвер мовчки падає на запасний шлях «по байту
 *    через чергу», а та черга при переповненні **мовчки викидає байти**
 *    (`stm32_serial_send_byte`: `if (_fifo_full(...)) return;`). Тобто кадр
 *    поїхав би обрізаним, і побачив би це лише CRC на тому боці.
 *
 *    Тому буфер оголошений з `__DMA` — це макрос самого EdgeTX
 *    (`targets/common/arm/stm32/f4/memory_sections.h`), який кладе змінну в
 *    `.ram` і вирівнює на 4. Доказ, що це справді спрацювало, — карта пам'яті,
 *    а не це речення.
 *
 * ============================================================================
 *
 * Ще дві межі, які варто мати на увазі.
 *
 * **Порожній канал.** Поки з того боку тиша, транспорт не передає нічого: ані
 * плиток, ані вітання. Над послідовним портом поняття «клієнт під'єднався» не
 * існує, а `HELLO` за специфікацією йде «при старті, при підключенні клієнта і
 * на запит» — над UART перших двох подій немає, тож лишається запит. Отже
 * першим говорить клієнт: `PING`, у відповідь `HELLO`, далі `REFRESH`.
 *
 * ⚠️ Це **наслідок** із docs/03-protocol.md, а не записане там правило. Для
 * автора моста це контракт, тому питання винесене в результат задачі 0009:
 * правило рукостискання над послідовним портом має стояти в специфікації.
 *
 * Пульт із портом у нашому режимі й порожнім роз'ємом працює точно так само,
 * як без нього.
 *
 * **Перемикання режиму порту на льоту — залишковий ризик, названий чесно.**
 * EdgeTX гасить попередній режим викликом `serialSetCallBacks(mode, nullptr,
 * port)` **після** того, як уже зробив `deinit()` драйвера. А
 * `stm32_serial_deinit()` не просто вимикає периферію: він викликає
 * `stm32_serial_free_state()`, тобто обнуляє весь стан порту разом із
 * `st->sp`. Ані `getByte()`, ані `txCompleted()`, ані `sendBuffer()` цей
 * вказівник не перевіряють.
 *
 * Тобто між `deinit()` і нашим гачком ворота `s_linkUp` **законно підняті**, а
 * `s_ctx` уже вказує на обнулений стан. Прохід, що влучив у цей проміжок,
 * відпрацює цілком проти `st->sp == nullptr`: візьме звідти сміття як адреси (на
 * STM32F429 нульова адреса аліасована на флеш, тож негайного відмовляння може й
 * не бути) і налаштує прямий доступ до пам'яті за довільними регістрами. Це не
 * «запис у вимкнений USART», це запис куди завгодно, і називати це м'якше було б
 * неправдою.
 *
 * ⚠️ Вікно — **цілий прохід**, і скоротити його перевірками воріт не можна:
 * гачок виконується в menusTask (пріоритет 1), а наша задача (2) усередині
 * проходу процесором не поступається жодного разу. Тобто menusTask фізично не
 * може витіснити прохід, і зайві перевірки посеред нього нічого не побачили б.
 * Ворота перевіряються один раз на прохід — рівно там, де це має сенс.
 *
 * Чому це прийнято, а не закрито. Проміжок відкривається лише при
 * **повторній** ініціалізації порту, тобто при зміні режиму на льоту, а
 * зробити це можна тільки з меню — на пульті з розбитим екраном його немає.
 * При старті `state->port` нульовий, тож `deinit()` не викликається взагалі.
 * Дешевий запобіжник на майбутнє, якщо екран колись з'явиться: перевіряти в
 * проході `serialGetMode(SP_AUX1) == UART_MODE_REMOTE_UI` — обидва місця, які
 * міняють режим, пишуть налаштування **до** `serialInit()`, тому транспорт
 * побачив би зміну ще до `deinit()`. Рішення відкрите до перегляду.
 */

