/*
 * TX16S Remote UI — стиснення RLE16.
 *
 * Ліцензія: GPLv2 (та сама, що в EdgeTX).
 *
 * Формат (docs/03-protocol.md): послідовність пар `[лічильник:1][піксель:2]`,
 * лічильник 1…255, піксель RGB565 little-endian.
 *
 * Серії рахуються по **лінійній** послідовності пікселів плитки, наскрізь
 * через межі рядків: у нашому буфері плитка лежить суцільно, і однотонна
 * плитка 32×32 стискається в 5 пар (1024 = 4×255 + 4) замість 32 по одній
 * на рядок.
 *
 * Цей шар нічого не знає ані про EdgeTX, ані про плитки — тільки масив
 * пікселів на вході й байти на виході. Тому він повністю перевіряється
 * тестами на ПК.
 */

#pragma once

#include <stddef.h>
#include <stdint.h>

namespace remote_ui {

// Найгірший випадок: жодного повтору, 3 байти на кожен піксель.
constexpr size_t RLE16_WORST_CASE_BYTES_PER_PIXEL = 3;

// Стискає `count` пікселів у `out`.
//
// Повертає кількість записаних байтів або **0**, якщо стиснуте не вмістилось
// у `outSize` (а також при count == 0 чи хибних вказівниках). Нуль — це не
// помилка, а звичайний робочий результат: викликач у цьому разі шле плитку
// сирою (метод 0). Саме так реалізується правило «стиснуте більше за сире —
// шлемо сире»: викликач дає `outSize` на байт менший за сирий розмір, і
// кодувальник сам зупиняється, щойно перестає бути вигідним.
//
// Нічого не виділяє: уся пам'ять приходить ззовні.
size_t rle16Encode(const uint16_t* pixels, size_t count, uint8_t* out,
                   size_t outSize);

// Зворотне перетворення. Потрібне тестам («туди-назад») і тестовому клієнту;
// у прошивці не використовується, бо розпаковує клієнт.
//
// Повертає кількість відновлених пікселів або 0, якщо потік битий: довжина не
// кратна 3, лічильник 0 або пікселів вийшло більше за `outPixels`.
size_t rle16Decode(const uint8_t* data, size_t len, uint16_t* out,
                   size_t outPixels);

}  // namespace remote_ui
