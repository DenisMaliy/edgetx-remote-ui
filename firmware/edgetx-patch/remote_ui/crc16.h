/*
 * TX16S Remote UI — CRC-16/CCITT-FALSE.
 *
 * Ліцензія: GPLv2 (та сама, що в EdgeTX).
 *
 * Окрема одиниця трансляції навмисно: контрольну суму треба вміти перевірити
 * тестом із відомою відповіддю, не тягнучи за собою решту протоколу.
 *
 * Параметри алгоритму (саме CCITT-FALSE, а не «CRC-16 CCITT» взагалі):
 *   поліном  0x1021
 *   початок  0xFFFF
 *   рефлексія входу/виходу — немає
 *   xorout   0x0000
 *   контрольний вектор: "123456789" -> 0x29B1
 *
 * Реалізація побітова, без таблиці на 512 байт. Річ не в розмірі таблиці —
 * EdgeTX уже містить свою для цього самого полінома (`radio/src/crc.cpp`,
 * `crc16tab_1021`), і вона потрапляє в кожну збірку незалежно від нас. Річ
 * у вимозі задачі 0004: цей шар не має права залежати від жодного
 * заголовка EdgeTX, а взяти чужу таблицю — значить прив'язатися. Ціна
 * восьми зсувів на байт на потоці ~92 КБ/с (921600 бод) непомітна.
 */

#pragma once

#include <stddef.h>
#include <stdint.h>

namespace remote_ui {

// Початкове значення регістра CRC.
constexpr uint16_t CRC16_INIT = 0xFFFF;

// Поліном CCITT (x^16 + x^12 + x^5 + 1).
constexpr uint16_t CRC16_POLY = 0x1021;

// Додає один байт до вже накопиченої контрольної суми.
// Саме цим викликом рахує декодувальник — по байту, без буферування «сирих»
// байтів заради пізнішого підрахунку.
uint16_t crc16Update(uint16_t crc, uint8_t byte);

// Зручна обгортка для суцільного блока пам'яті.
// Якщо data == nullptr, блок вважається порожнім і повертається seed.
uint16_t crc16(const uint8_t* data, size_t len, uint16_t seed = CRC16_INIT);

}  // namespace remote_ui
