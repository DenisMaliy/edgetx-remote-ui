#pragma once

#include <stdint.h>

// Гачок захоплення екрана.
//
// Викликається з `flushLcd()` (`radio/src/gui/colorlcd/lcd.cpp`), на самому
// початку функції — до раннього виходу для цілей із прямим режимом LVGL, щоб
// на всіх цілях приходили **всі** змінені області, а не лише остання.
//
// Параметри свідомо прості (int і uint16_t*), а не типи LVGL: так наш код
// лишається без залежності від LVGL, а перехід LVGL 8 -> 9 зачіпає рівно один
// рядок у чужому файлі, а не нашу бібліотеку.
//
//   x1, y1, x2, y2 — межі зміненої області **включно**, логічні (неповернуті)
//                    координати екрана;
//   pixels         — пікселі цієї області RGB565, щільно, крок рядка =
//                    ширині області (x2 - x1 + 1);
//   isLast         — ознака останньої області кадру: після неї картинка
//                    цілісна, і клієнту можна слати FRAME_END.
//
// Виконується в задачі `menusTask` — найнижчий пріоритет, мікшер витісняє її
// будь-коли. Тому всередині лише копіювання й позначення плиток; стиснення,
// кадрування й передача — в іншому потоці.
void remoteUiOnFlush(int x1, int y1, int x2, int y2, const uint16_t* pixels,
                     bool isLast);

// --- Емульований ввід -------------------------------------------------------
//
// Підмішується не в інтерфейс, а в **драйвери** — там, де EdgeTX читає залізо.
// Тому довге натискання, автоповтор і прискорення енкодера рахує сам EdgeTX,
// а ми їх не програмуємо (state/DECISIONS.md, 2026-07-25).
//
// ⚠️ Жодна з цих функцій не заступає фізичний ввід: клавіші й тримери
// додаються до прочитаних із заліза, енкодер зсуває положення, а сенсор
// віддається фізичному драйверу, щойно віддалений дотик завершився.
//
// ⚠️ Тиша в каналі понад INPUT_RELEASE_TIMEOUT_MS (input.h) відпускає все сама,
// без жодного пакета й без участі транспорту: відпускає читач, а не той, хто
// натискав. Тобто обрив каналу клавішу натиснутою не лишає — але **втрачений
// поодинокий пакет «відпущено» при живому зв'язку не ловить ніхто**. Межа
// гарантії й що з нею робити — на початку input.h.

// Гачок 6, `keysPollingCycle()` у `radio/src/keys.cpp`:
//   keys_input  |= remoteUiGetKeys();
//   trims_input |= remoteUiGetTrims();
//
// Маска клавіш — біти за `EnumKeys`, маска тримерів — за напрямками
// (`trim_keys`, по два біти на тример). Обидві вже звірені з тим, що ціль
// справді має: чужі біти не проходять.
uint32_t remoteUiGetKeys();
uint32_t remoteUiGetTrims();

// Гачок 7, `rotaryDriverRead()` у `radio/src/gui/colorlcd/LvglWrapper.cpp`:
//   newPos += remoteUiGetEncoderOffset();
//
// ⚠️ Саме **накопичене положення**, а не приріст від минулого разу. EdgeTX
// рахує різницю з попереднім читанням і запам'ятовує суму сам; віддавши раз
// «+3» і потім нуль, ми породили б фантомний оберт назад на ті самі три
// клацання. Тому значення тільки росте (чи спадає) і при розриві не
// обнуляється.
int32_t remoteUiGetEncoderOffset();

// Гачок 7, там же, другим рядком:
//   remoteUiAddEncoderDt(&rotencDt);
//
// Прискорення ручки EdgeTX рахує з часу між клацаннями, накопиченого в
// `rotencDt`. Наш шлях цей лічильник не рухав, тому `dt` виходило нульовим,
// EdgeTX вважав, що ручку крутять нескінченно швидко, і прискорення застигало
// на максимумі: з другого клацання підряд крок стрибав на кілька десятків, і
// «покрутити на кілька одиниць» ставало неможливо.
//
// ⚠️ Приймає **вказівник на чужий лічильник**, а не повертає число під
// `rotencDt += ...`. Причина не в стилі: `rotencDt` пише ще й переривання
// енкодера, а «прочитати-додати-записати» з задачі — не атомарна операція.
// Тримаючи запис у себе, ми можемо не робити його зовсім, поки віддалених
// клацань немає, — і тоді без клієнта фізична ручка працює точно як раніше.
void remoteUiAddEncoderDt(volatile uint32_t* rotencDt);

// Гачок 7, `touchDriverRead()` у тому ж файлі, **до** читання фізичного
// сенсора: віддалений дотик має обходити умову `if (!isBacklightEnabled())`,
// інакше клієнт не зміг би розбудити пульт зі згаслою підсвіткою — а це
// найперше, що зробить людина, взявши телефон.
//
// Повертає false, коли віддаленого дотику немає: тоді драйвер читає залізо,
// як завжди. Поки дотик триває, повертає true на кожен виклик — LVGL має
// бачити натиск усі опитування підряд.
//
// Типи LVGL сюди не потрапляють навмисно (те саме рішення, що й для гачка
// захоплення): розбір `lv_indev_data_t` лишається в чужому файлі.
bool remoteUiPopTouch(int16_t* x, int16_t* y, bool* pressed);
