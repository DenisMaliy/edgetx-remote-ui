/*
 * TX16S Remote UI — захоплення екрана: тіньовий кадр і брудні плитки.
 *
 * Ліцензія: GPLv2 (та сама, що в EdgeTX).
 *
 * Двоє учасників і жодного м'ютекса:
 *
 *   гачок (menusTask)        captureOnFlush()    копіює пікселі, ставить біти
 *   транспорт (свій потік)   captureTakeTile()   знімає біт, забирає плитку
 *
 * Чому без блокування. Гачок стоїть у задачі з найнижчим пріоритетом, яку
 * мікшер витісняє будь-коли; чекати на м'ютекс він не має права. Тому порядок
 * дій підібраний так, що втратити зміну неможливо:
 *
 *   гачок:      спершу пікселі в тіньовий кадр, **потім** біт «брудна»;
 *   транспорт:  спершу зняти біт, **потім** читати пікселі.
 *
 * Якщо гачок утрутиться між зняттям біта й читанням, транспорт віддасть
 * плитку, зшиту з двох кадрів, — але біт уже стоїть знову, і наступним
 * проходом піде цілісна. Переповнення самої карти не буває за побудовою:
 * це бітова карта фіксованого розміру, а не буфер, який може скінчитись.
 *
 * ⚠️ Межа гарантії. Карта не губить нічого, але плитка, вже **забрана**
 * транспортом, живе поза нею. Якщо транспорт не зміг її відправити (немає
 * місця в буфері передачі, розрив), він **зобов'язаний** повернути її
 * викликом captureReturnTile() — інакше зміна зникне тихо. Саме цей випадок
 * описує правило зворотного тиску в docs/02-architecture.md.
 *
 * ⚠️ Формально одночасні memcpy у s_shadow і з нього — це гонка даних, і
 * ThreadSanitizer так і скаже. Виняток свідомий і стосується лише кадрового
 * буфера: наслідок гонки — зшита з двох кадрів плитка, яку наступний прохід
 * замінить цілісною. Ціна повного блокування тут — затримка гачка в задачі,
 * яку витісняє мікшер, і вона дорожча.
 */

#pragma once

#include <stddef.h>
#include <stdint.h>

#include "geometry.h"
#include "tile.h"

namespace remote_ui {

// Приймає змінену область від гачка. Координати включно, pixels — щільний
// масив (x2-x1+1) * (y2-y1+1) пікселів RGB565.
//
// Область, що вилазить за межі екрана, обрізається; повністю зовнішня
// відкидається. Гачок стоїть у чужому коді, тому перевірка тут дешевша за
// довіру.
void captureOnFlush(int x1, int y1, int x2, int y2, const uint16_t* pixels,
                    bool isLast);

// Забирає одну брудну плитку: заповнює `tile` і копіює її пікселі в `out`
// (потрібно щонайменше TILE_MAX_PIXELS елементів).
//
// Повертає false, якщо брудних плиток немає або буфер замалий. Обхід іде по
// колу від місця, де зупинився минулого разу, щоб одна плитка, яку
// перемальовують щокадру, не заступала решту.
bool captureTakeTile(TileRef& tile, uint16_t* out, size_t outPixels);

// Повертає забрану плитку в брудні: транспорт її взяв, але відправити не
// зміг. Без цього виклику зміна пропаде — див. межу гарантії вгорі файлу.
void captureReturnTile(const TileRef& tile);

// Позначає весь екран брудним: підключення клієнта і команда REFRESH.
void captureMarkAllDirty();

// Лічильник завершених кадрів (гачок з isLast = true). Транспорт порівнює
// його зі своїм останнім значенням і так розуміє, коли слати FRAME_END.
// Переповнення нешкідливе: порівнюється на нерівність.
uint32_t captureFrameCount();

// Скільки плиток зараз брудні. Для тестів і діагностики.
uint32_t captureDirtyCount();

// Повертає захоплення в початковий стан. Потрібно тестам, щоб вони не
// впливали один на одного; у прошивці не викликається.
void captureReset();

}  // namespace remote_ui
