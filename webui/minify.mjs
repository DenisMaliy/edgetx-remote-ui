// Мініфікація клієнта перед вбудовуванням у прошивку моста.
//
// ⚠️ Це не косметика, а лікування заміряної вади (задача 0022, критерій 8.3).
// Після появи бокових панелей сторінка на дроті виросла 43.4 → 57.8 КБ gzip, і
// холодне завантаження опустило вільну купу моста до **20.5 КБ** при межі
// тривоги 32.8 КБ — заміряно тричі на стенді, не порахувано.
//
// ⚠️ Українські коментарі з джерела **не ріжуться**. Вони лишаються в
// `webui/*.js`, де їх читають люди, і зникають із того примірника, що їде у
// флеш. Рішення людини від 2026-08-02: пояснення — частина коду.
//
// ⚠️ **Виняток — `index.html`: він лише копіюється** (див. `COPY` нижче), тож
// його коментарі їдуть у флеш як є. Це не забудькуватість, а вибір: esbuild
// HTML не вміє, а різати коментарі регулярним виразом — спосіб колись
// зачепити `<!--` усередині рядка. Ціна винятку заміряна: розлогий абзац
// пояснення в розмітці коштував **236 Б** на дроті, скорочений до вказівника
// (той, що лежить там зараз) — **157 Б**.
//
// Чому саме так, а не інакше:
//
// * **`--charset=utf8`, не типовий ascii.** Типово esbuild екранує кирилицю в
//   `\uXXXX`, і кожна літера інтерфейсу стає шістьма байтами. Після gzip
//   різниця мала (16 031 проти 15 873 Б), але екранований файл ще й нечитний
//   очима, коли доводиться дивитись у те, що справді поїхало в пульт.
// * **`--target=esnext`, тобто синтаксис не перетворюється взагалі.** Джерело
//   вже працює в браузерах, які ми обслуговуємо; будь-яке зниження рівня мови
//   було б ризиком без вигоди.
// * **`index.html` не чіпається.** esbuild HTML не вміє, а різати коментарі
//   регулярним виразом — спосіб колись зачепити `<!--` усередині рядка.
//   Виграш там ~1 КБ із 18.5, тобто ризик дорожчий за здобуток.
//
// --- Чому це безпечно, і чому саме з цієї причини -------------------------
//
// ⚠️ **Гарантію дає `bundle: false`, і більше ніщо.** Для незібраного файлу
// верхній рівень і є глобальна область, тому esbuild верхньорівневих імен не
// перейменовує взагалі — а саме ними наші файли й спілкуються між собою
// (`RemoteUI`, `RemoteUIWait`, `RemoteUIPanels`).
//
// ⚠️ **Спокуслива, але хибна причина, якою це пояснювали спершу:** «кожен
// модуль загорнутий в IIFE, тож перейменування нікуди не витікає». Для
// `proto.js`, `wait.js` і `panels.js` це правда, **а для `app.js` — ні**: у
// нього обгортки немає, увесь його верхній рівень лежить у глобальній
// області. І це найбільший файл із шести. Хибне пояснення небезпечніше за
// відсутнє: воно виглядає як дозвіл чіпати `bundle`.
//
// Решта перевірена окремо: у `index.html` немає вбудованих обробників
// (`onclick=`), у коді немає `constructor.name`, `eval` і `.toString()`, а
// всі `.name` — це поля клавіш із `HELLO`, а не `Function.prototype.name`.
//
// Запуск: node minify.mjs <тека-призначення>

import * as esbuild from 'esbuild';
import { copyFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));

// ⚠️ Перелік має збігатися з `WEBUI_FILES` у firmware/esp32/main/CMakeLists.txt.
// ⚠️ Новий файл клієнта додається у **чотирьох** місцях:
//   1. тут (`MINIFY` або `COPY`);
//   2. `WEBUI_FILES` у `firmware/esp32/main/CMakeLists.txt`;
//   3. оголошення `extern` і шлях у `firmware/esp32/main/ws_bridge.c`;
//   4. `ASSETS` у `tools/webui_built_check.py` — інакше сторож звірятиме
//      п'ять файлів із шести й пропустить саме новий.
const MINIFY = ['proto.js', 'wait.js', 'panels.js', 'app.js', 'style.css'];
const COPY = ['index.html'];

const outDir = process.argv[2];
if (!outDir) {
  console.error('вжиток: node minify.mjs <тека-призначення>');
  process.exit(2);
}

await mkdir(outDir, { recursive: true });

for (const name of MINIFY) {
  await esbuild.build({
    entryPoints: [join(HERE, name)],
    outfile: join(outDir, name),
    minify: true,
    charset: 'utf8',
    target: 'esnext',
    legalComments: 'none',
    // ⛔ **НЕ МІНЯТИ на `true` і не додавати `format`.** Це не налаштування
    // смаку, а єдине, що тримає сторінку живою: з `bundle: true` (або з
    // будь-яким `format`) esbuild вважає верхній рівень локальною областю й
    // перейменовує його. Для `app.js`, який не загорнутий в IIFE, це означає
    // втрату `RemoteUI`, `Wait`, `Panels` і всіх його верхньорівневих імен —
    // сторінка помре повністю, а не частково.
    //
    // Побічно збирання зламало б і `wait_test.js`/`panels_test.js`: вони
    // беруть ті самі джерела через `require` у node.
    bundle: false,
    logLevel: 'warning',
  });
}

for (const name of COPY) {
  await copyFile(join(HERE, name), join(outDir, name));
}
