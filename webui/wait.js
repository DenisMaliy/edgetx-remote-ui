'use strict';
/*
 * Політика показу кадру: чекати доїзду решти плиток чи показувати негайно.
 *
 * ⚠️ Модуль **без жодного дотику до DOM**: ні полотна, ні таймерів, ні
 * `performance.now()`. Час приходить параметром `now`, таймер заводить той,
 * хто викликав. Так автомат прогоняється тестами під node і — тими самими
 * сценаріями — своїм близнюком на Python (`tools/remote_ui_proto.py`).
 *
 * Причина винесення названа рецензією 0019: `webui/app.js` не покритий нічим,
 * а дзеркальність двох клієнтів трималась на читанні очима. Одну розбіжність
 * це вже коштувало.
 *
 * --------------------------------------------------------------------------
 * Головне правило (задача 0020): чекати чи ні — вирішує **джерело вводу**, а
 * не кількість плиток.
 *
 * Поріг за кількістю плиток закритий числами 2026-08-02: `dirtyTiles` ніколи
 * не наближається до розміру сітки, а режими керування лежать в одному
 * діапазоні 80–96 і порогом не розділяються. Тому важіль інший — клієнт
 * **сам щойно надіслав** `TOUCH` або `ENC` і знає, чим керують.
 *
 * При клацанні енкодера людина дивиться на **чіткість** кадру; при протягу
 * пальцем — на **рух**. Звідси:
 *
 *   протяг пальцем (і хвіст інерції за ним)  →  показ негайно, шов дозволено
 *   енкодер, клавіша, тик пальцем, тиша      →  чекаємо цілого кадру
 */
(function (root) {

const P = (typeof module !== 'undefined' && module.exports)
  ? require('./proto.js')
  : root.RemoteUI;

// --------------------------------------------------------------- режими ----
//
// Три положення кнопки «чек» лишаються з 0019 як **прилад** для порівняння
// оком, а не як налаштування на щодень. Типове — `завжди`.

const WAIT_OFF = 0;      // показ на кожному FRAME_END — поведінка до 0019
const WAIT_LIMIT = 1;    // очікування, поки залишок не більший за поріг
const WAIT_ALWAYS = 2;   // очікування завжди; тримає лише стеля

// -------------------------------------------------------- джерела вводу ----

const SRC_NONE = 'none';    // вводу не було взагалі: пульт перемальовує сам
const SRC_TOUCH = 'touch';  // сенсор
const SRC_ENC = 'enc';      // енкодер
const SRC_KEY = 'key';      // клавіша

/* ⚠️ Скільки тримати режим «не чекати» після **останнього** пакета дотику.
 *
 * «Поки палець на екрані» замало, і це не здогад: людина відпускає палець, а
 * список їде далі сам. Число виведене з коду LVGL, який лежить у нашому ж
 * `upstream/edgetx`, а не з відчуття:
 *
 *   - інерція увімкнена типово — `lv_obj.c:452` ставить
 *     `LV_OBJ_FLAG_SCROLL_MOMENTUM` у конструкторі об'єкта;
 *   - швидкість гасне на кожному опитуванні сенсора:
 *     `v = v * (100 − scroll_throw) / 100`, цілочисельно
 *     (`lv_indev_scroll.c:_lv_indev_scroll_throw_handler`);
 *   - `scroll_throw` = 10 (`lv_hal_indev.h:33`), EdgeTX його не перекриває;
 *   - опитування сенсора — раз на 30 мс (`colorlcd/lv_conf.h:105`).
 *
 * Тобто хвіст інерції = стільки кроків ×0.9, скільки треба, щоб ціле число
 * впало до нуля, помножити на 30 мс:
 *
 *   поштовх 24 px/період (≈800 px/с) → 16 періодів → 480 мс
 *   поштовх 50                       → 22          → 660 мс
 *   поштовх 127 (стеля правдоподібного) → 30       → 900 мс
 *
 * Плюс доїзд до краю списку (`lv_obj_scroll_by(..., LV_ANIM_ON)`), який
 * додається зверху. Отже 1000 мс покриває найшвидший поштовх із запасом.
 *
 * ⚠️ Перебрати тут майже безкоштовно, і це важливо для розуміння числа: коли
 * картинка **вгамувалась**, `dirtyTiles` дорівнює нулю, і до правила про
 * джерело виконання просто не доходить — цілий кадр показується негайно за
 * своєю власною гілкою. Тобто зайві сотні мілісекунд вікна нічого не коштують
 * на нерухомому екрані; коштувало б занижене число — воно ввімкнуло б
 * очікування посеред інерційного гортання, тобто рівно там, де рух і видно. */
const TOUCH_NOWAIT_MS = 1000;

/* ⚠️ Вікно «не чекати» відкриває **протяг**, а не будь-який дотик.
 *
 * Тик пальцем по пункту меню — це разовий перехід, а не рух: людина дивиться
 * на нову сторінку, а не проводжає її очима. Він ближчий до клацання
 * енкодера, ніж до гортання, і головна ідея задачі («енкодер — чіткість,
 * протяг — рух») відносить його до чіткості. Інерції в нього теж немає:
 * гасити нічого.
 *
 * Поріг — 10 пікселів екрана пульта, і це **не наше вигадане число**, а той
 * самий `LV_INDEV_DEF_SCROLL_LIMIT` (`lv_hal_indev.h:30`), яким сам LVGL
 * відрізняє гортання від натискання. Клієнт вирішує так само, як вирішить
 * пульт, — інакше жест, який пульт уже вважає гортанням, у нас лишався б
 * «тиком». EdgeTX цього числа не перекриває.
 *
 * Помилка в цьому порозі не небезпечна: найгірше — короткий протяг покажеться
 * як тик, тобто з очікуванням, як було до задачі. */
const TOUCH_DRAG_LIMIT_PX = 10;

// ----------------------------------------------------- причини показу ------
//
// ⚠️ Взаємовиключні за побудовою: рівно одна причина на показаний кадр.
// Клієнт рахує їх окремими лічильниками, і рівність «сума причин = кадрів»
// стереже тест. Розширювати перелік — тільки разом із лічильником.

const WHY_LEGACY = 'legacy';    // прошивка без ознаки повноти (до 0019)
const WHY_WHOLE = 'whole';      // dirtyTiles = 0 — кадр цілісний
const WHY_OFF = 'off';          // очікування вимкнене кнопкою
const WHY_DRAG = 'drag';        // палець веде: рух важливіший за шов
const WHY_TOO_MANY = 'toomany'; // залишок понад поріг — чекати нема сенсу
const WHY_TIMEOUT = 'timeout';  // решта не доїхала за строк

/**
 * Автомат очікування.
 *
 * Порядок виклику з боку клієнта:
 *
 *   при надсиланні вводу      → noteInput(джерело, now, x, y)
 *   на кожному FRAME_END      → decide(dirtyTiles, now)
 *   у мить, коли показали кадр → noteShown()
 *
 * `decide()` повертає `{show, waitMs, why}`. При `show === false` той, хто
 * викликав, заводить таймер на `waitMs` і показує кадр після нього з причиною
 * `WHY_TIMEOUT` — автомат таймерів не має.
 */
class FrameWaitPolicy {
  constructor(opts) {
    const o = opts || {};
    this.mode = o.mode === undefined ? WAIT_ALWAYS : o.mode;

    // Швидкість каналу приходить у HELLO і міняється на ходу; від неї
    // рахується поріг. `null` = HELLO ще не було.
    this.baud = o.baud === undefined ? null : o.baud;

    // Джерело останнього вводу — те, що клієнт **сам надіслав**.
    this.lastSource = SRC_NONE;
    this.lastInputAt = 0;

    // Жест пальцем: чи зрушив він далі за поріг гортання.
    this.touchDown = false;
    this.touchDragging = false;
    this.touchStartX = 0;
    this.touchStartY = 0;

    // Низка очікування: мить першого відкладеного кадру й ознака, що показ
    // зараз відкладений.
    this.pending = false;
    this.waitingSince = 0;

    /* ⚠️ Вимикач самого правила протягу — **прилад для сліпого порівняння**, а
     * не налаштування. Кнопки в панелі він навмисно не має: критерій 2.3
     * вимагає, щоб людина не знала, який режим увімкнено, а видима кнопка це
     * знання їй і дала б. Тому вимикач смикає сценарій із ПК
     * (`window.remoteUiDragRule`), а стан друкується в панелі «Стан» — щоб
     * знімок-доказ усе одно казав, у якому режимі його знято.
     *
     * Вимкнене правило = поведінка рівно до задачі 0020. */
    this.dragRule = o.dragRule === undefined ? true : o.dragRule;
  }

  setMode(mode) { this.mode = mode; }
  setBaud(baud) { this.baud = baud === undefined ? null : baud; }
  setDragRule(on) { this.dragRule = !!on; }

  /** Поріг залишку в плитках. Без HELLO віддає запасне число з proto.js. */
  tileLimit() { return P.frameWaitTileLimit(this.baud); }

  /**
   * Клієнт щойно надіслав ввід.
   *
   * `source` — одне з SRC_TOUCH / SRC_ENC / SRC_KEY. Для дотику потрібні ще
   * `x`, `y` в пікселях пульта і `phase` — 'down' | 'move' | 'up'.
   *
   * ⚠️ Сюди йде тільки **справжній ввід людини**. Періодичний `INPUT_STATE`
   * повторює рівень і вводом не є: інакше утримуваний палець нескінченно
   * подовжував би вікно «не чекати» вже після того, як усе зупинилось.
   */
  noteInput(source, now, opts) {
    const o = opts || {};
    this.lastSource = source;
    this.lastInputAt = now;

    if (source !== SRC_TOUCH) {
      // Енкодер або клавіша посеред жесту — жест скінчився. Інакше вікно
      // «не чекати», відкрите протягом, лишалось би висіти на клацаннях.
      this.touchDown = false;
      this.touchDragging = false;
      return;
    }

    if (o.phase === 'down') {
      this.touchDown = true;
      this.touchDragging = false;
      this.touchStartX = o.x || 0;
      this.touchStartY = o.y || 0;
      return;
    }

    if (o.phase === 'move' && this.touchDown && !this.touchDragging) {
      const dx = (o.x || 0) - this.touchStartX;
      const dy = (o.y || 0) - this.touchStartY;
      if (Math.abs(dx) >= TOUCH_DRAG_LIMIT_PX
          || Math.abs(dy) >= TOUCH_DRAG_LIMIT_PX) {
        this.touchDragging = true;
      }
      return;
    }

    if (o.phase === 'up') {
      // ⚠️ Палець відпущено, але `touchDragging` **не гаситься**: саме тут
      // починається інерція, і вікно має пережити її. Гасить його наступний
      // `down` або чужий ввід.
      this.touchDown = false;
    }
  }

  /** Чи діє зараз правило «не чекати». Це і є весь критерій 1 однією умовою. */
  dragging(now) {
    if (!this.dragRule) return false;   // прилад сліпого порівняння, див. вище
    if (!this.touchDragging) return false;
    if (this.touchDown) return true;              // палець ще на екрані
    return (now - this.lastInputAt) <= TOUCH_NOWAIT_MS;   // хвіст інерції
  }

  /**
   * `FRAME_END` прийшов. `dirty` — скільки плиток ще в дорозі, або `null`,
   * якщо прошивка стара і ознаки повноти не має.
   */
  decide(dirty, now) {
    if (dirty === null) return this._show(WHY_LEGACY);

    // ⚠️ Цілий кадр — завжди негайно, поперед усіх правил. Будь-яке
    // відкладання тут є чистим зростанням затримки від дотику до екрана.
    if (dirty === 0) return this._show(WHY_WHOLE);

    // Очікування вимкнене кнопкою — прилад для порівняння оком.
    if (this.mode === WAIT_OFF) return this._show(WHY_OFF);

    // Головне правило задачі 0020: палець веде — показуємо негайно.
    if (this.dragging(now)) return this._show(WHY_DRAG);

    // Запобіжник 0019: залишок не встигне доїхати раніше, ніж пульт
    // перемалює кадр наново. У режимі `завжди` цієї гілки немає зовсім.
    if (this.mode === WAIT_LIMIT && dirty > this.tileLimit()) {
      return this._show(WHY_TOO_MANY);
    }

    // ⚠️ Стеля рахується від початку **поточної низки** очікування — не від
    // кожного FRAME_END (екран замерз би назавжди на безперервному гортанні) і
    // не від останнього показаного кадру (після паузи запас був би вже
    // вичерпаний, і перший же неповний кадр показався б без очікування).
    if (!this.pending) this.waitingSince = now;

    const waitMs = Math.min(P.frameWaitMs(dirty),
                            this.waitingSince + P.FRAME_WAIT_MAX_MS - now);
    if (waitMs <= 0) return this._show(WHY_TIMEOUT);

    this.pending = true;
    return { show: false, waitMs: waitMs, why: null };
  }

  /** Кадр показано — байдуже, за якою причиною. Низка очікування скінчилась. */
  noteShown() { this.pending = false; }

  /**
   * Забути відкладений кадр **без показу**: з'єднання померло або екран
   * змінив розмір, і чекати вже нема на що.
   *
   * ⚠️ Окремий іменований метод, а не `noteShown()` на місці виклику, і не
   * дрібниця. Обидва клієнти мусять звати **одне й те саме** — у клієнта ПК
   * цей виклик був, у браузері його забули, і наслідок був тихий: `pending`
   * і `waitingSince` переживали розрив, тож перший же неповний кадр після
   * кожного перепідключення показувався зшитим і рахувався «за строком» —
   * тобто домішка в той самий лічильник, на якому стоять рішення про
   * очікування.
   *
   * ⚠️ Не кликати в звичайному ході `decide()`: там низка живе далі, і
   * скидання стелі перетворило б її на нескінченну.
   */
  forget() { this.pending = false; }

  _show(why) {
    this.pending = false;
    return { show: true, waitMs: 0, why: why };
  }
}

// ---------------------------------------------------------------- вихід ----

const RemoteUIWait = {
  WAIT_OFF, WAIT_LIMIT, WAIT_ALWAYS,
  SRC_NONE, SRC_TOUCH, SRC_ENC, SRC_KEY,
  TOUCH_NOWAIT_MS, TOUCH_DRAG_LIMIT_PX,
  WHY_LEGACY, WHY_WHOLE, WHY_OFF, WHY_DRAG, WHY_TOO_MANY, WHY_TIMEOUT,
  FrameWaitPolicy,
};

if (typeof module !== 'undefined' && module.exports) {
  module.exports = RemoteUIWait;   // node: wait_test.js, wait_trace.js
} else {
  root.RemoteUIWait = RemoteUIWait;   // браузер: app.js
}

})(typeof globalThis !== 'undefined' ? globalThis : this);
